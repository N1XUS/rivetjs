// Generate the native event list shared by the compiler and the JSX types from TypeScript's
// lib.dom.d.ts (`HTMLElementEventMap` and the maps it extends; legacy `webkit*` names skipped).
// Outputs (checked in; rerun after a TypeScript upgrade):
//   libs/compiler/rust/src/events_data.rs  — (JSX name, DOM type) pairs for `on<Name>`
//   libs/runtime/jsx-events.ts             — the `EventMap` type of the JSX runtime
// Usage: node scripts/gen-events.mjs [--check]   (--check: fail if the outputs are stale)
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const root = new URL("../", import.meta.url);
const lib = readFileSync(createRequire(root).resolve("typescript/lib/lib.dom.d.ts"), "utf8");

/** interface name → { extends, entries: [dom name, event type] } */
const interfaces = new Map();
for (const match of lib.matchAll(/^interface (\w+EventMap)(?: extends ([\w, ]+))? \{\n([\s\S]*?)^\}/gm)) {
  const entries = [...match[3].matchAll(/^\s+"([a-z]+)": (\w+);/gm)].map((m) => [m[1], m[2]]);
  const previous = interfaces.get(match[1]);
  interfaces.set(match[1], {
    extends: [...(previous?.extends ?? []), ...(match[2] ? match[2].split(",").map((s) => s.trim()) : [])],
    entries: [...(previous?.entries ?? []), ...entries],
  });
}
const events = new Map();
const collect = (name) => {
  const entry = interfaces.get(name);
  if (!entry) throw new Error("lib.dom.d.ts has no " + name);
  for (const parent of entry.extends) collect(parent);
  for (const [event, type] of entry.entries) if (!event.startsWith("webkit")) events.set(event, type);
};
collect("HTMLElementEventMap");

// Rivet keeps narrower handler types where lib.dom is wider than what the elements dispatch.
const overrides = { input: "InputEvent", error: "Event" };
// Words of DOM event names, for the PascalCase JSX names (longest match first).
const words = (
  "abort animation aux before blur cancel can capture change click close composition content context copy cue cut data " +
  "dbl down drag drop duration emptied end ended enter error focus form fullscreen got in input invalid iteration key " +
  "leave load loaded lost match menu metadata mouse move out over paste pause play playing pointer policy press progress " +
  "rate raw reset resize restored run scroll security seeked seeking select selection slot stalled start submit suspend " +
  "through time toggle touch transition up update violation volume waiting wheel"
)
  .split(" ")
  .sort((a, b) => b.length - a.length);
const pascal = (event) => {
  let out = "";
  for (let rest = event; rest; ) {
    const word = words.find((w) => rest.startsWith(w));
    if (!word) throw new Error(`gen-events: add a word for "${rest}" (from "${event}")`);
    out += word[0].toUpperCase() + word.slice(1);
    rest = rest.slice(word.length);
  }
  return out;
};
const list = [...events].map(([event, type]) => [pascal(event), event, overrides[event] ?? type]).sort((a, b) => (a[0] < b[0] ? -1 : 1));
const header = "Generated by scripts/gen-events.mjs from TypeScript's lib.dom.d.ts (HTMLElementEventMap). Do not edit.";

const rust =
  `// ${header}\n` +
  "/// Native events accepted as `on<Name>` / `on<Name>Capture`: (JSX name, DOM event type), sorted by name.\n" +
  "pub const EVENTS: &[(&str, &str)] = &[\n" +
  list.map(([name, event]) => `    ("${name}", "${event}"),\n`).join("") +
  "];\n";
const ts =
  `// ${header}\n` +
  "/** Native events the compiler accepts as `on<Name>` / `on<Name>Capture` (events_data.rs, same source). */\n" +
  "export type EventMap = {\n" +
  list.map(([name, , type]) => `  ${name}: ${type};\n`).join("") +
  "};\n";

const outputs = [
  [new URL("libs/compiler/rust/src/events_data.rs", root), rust],
  [new URL("libs/runtime/jsx-events.ts", root), ts],
];
if (process.argv.includes("--check")) {
  const stale = outputs.filter(([file, text]) => {
    try {
      return readFileSync(file, "utf8") !== text;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error("stale: " + stale.map(([f]) => f.pathname).join(", ") + " — run node scripts/gen-events.mjs");
    process.exit(1);
  }
  console.log(`events: ${list.length} names up to date`);
} else {
  for (const [file, text] of outputs) writeFileSync(file, text);
  console.log(`events: wrote ${list.length} names`);
}
