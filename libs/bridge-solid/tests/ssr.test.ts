import { test, expect } from "vitest";
import { createComponent } from "solid-js";
import { renderToString } from "solid-js/web";
import type { IslandContext, SlotMark } from "@rivetjs/bridge/adapter";
import { adapter } from "../server.ts";
import { Boom, Counter, LateBoom, Later } from "./fixtures/components.solid.tsx";

export const mark = (name: string): SlotMark => ({
  name,
  html: `<rivet-slot${name === "default" ? "" : ` name="${name}"`} style="display:contents"></rivet-slot>`,
});
const ctx = (id = "i0", nonce?: string): IslandContext => ({ id, nonce, signal: new AbortController().signal, slot: mark });

test("sync output uses Solid native SSR and distinct per-island hydration and unique ids", () => {
  const html = adapter.render(Counter, { count: 1 }, {}, ctx());
  expect(typeof html).toBe("string");
  expect(html).toBe(renderToString(() => createComponent(Counter, { count: 1 }), { renderId: "i0" }));
  expect(html).toMatch(/data-hk="i0/);
  const next = adapter.render(Counter, { count: 1 }, {}, ctx("i1")) as string;
  expect(/id="([^"]+)"/.exec(html as string)?.[1]).not.toBe(/id="([^"]+)"/.exec(next)?.[1]);
});

test("slots preserve the exact supplied HTML, including arbitrary escaped mark attributes", () => {
  const marks = { default: mark("default"), title: mark("title") };
  const html = adapter.render(Counter, {}, marks, ctx()) as string;
  for (const value of Object.values(marks)) expect(html.split(value.html)).toHaveLength(2);
});

test("head carries the CSP nonce, disables the Solid prehydration event recorder, and is request scoped", () => {
  const head = adapter.head!(ctx("i0", "solid-nonce"));
  expect(head).toContain('nonce="solid-nonce"');
  expect(head).toContain("_$HY");
  expect(head).not.toContain('["click", "input"]');
  expect(adapter.head!(ctx())).toContain("_$HY");
});

test("pending Suspense sentinel is recognized and async output contains resolved content", async () => {
  const probe = renderToString(() => createComponent(Later, { value: "later" }), { renderId: "probe" });
  expect(probe).toContain('="$$f"');
  const html = adapter.render(Later, { value: "late" }, {}, ctx());
  expect(html).toBeInstanceOf(Promise);
  expect(await html).toContain("late");
  expect(await html).not.toContain(">wait<");
});

test("sync and async errors propagate and the next island can still render", async () => {
  expect(() => adapter.render(Boom, {}, {}, ctx())).toThrow("solid boom");
  await expect(adapter.render(LateBoom, {}, {}, ctx())).rejects.toThrow("solid async boom");
  expect(adapter.render(Counter, { count: 7 }, {}, ctx("i7"))).toContain("7");
});

test("browser SSR fixtures equal native server output (regenerate explicitly after changing the fixture)", async () => {
  const { default: snapshot } = await import("./fixtures/ssr.ts");
  const fixtures: Record<string, string> = {};
  for (const id of ["i0", "i1", "i2"]) fixtures[id] = (await adapter.render(Counter, { count: 1, label: "first" }, {}, ctx(id))) as string;
  fixtures.later = (await adapter.render(Later, { value: "hydrated-async" }, {}, ctx("async"))) as string;
  fixtures.slots = (await adapter.render(Counter, { count: 1, label: "first" }, { default: mark("default"), title: mark("title") }, ctx())) as string;
  if (process.env.UPDATE_SOLID_FIXTURES === "1") {
    const { writeFile } = await import("node:fs/promises");
    await writeFile(
      new URL("./fixtures/ssr.ts", import.meta.url),
      `// Generated by UPDATE_SOLID_FIXTURES=1 vitest run --project bridge-solid tests/ssr.test.ts.\nexport default ${JSON.stringify(fixtures, null, 2)} as Record<string, string>;\n`,
    );
  } else expect(fixtures).toEqual(snapshot);
});
