import type { Key } from "../collections/index.ts";
import type { Rect } from "./rect.ts";

/**
 * Instances of this lightweight class are created by `Layout` subclasses to represent each item in the
 * `Virtualizer`: position, size and style information the virtualizer uses when rendering views.
 */
export class LayoutInfo {
  /** The type of element represented by this LayoutInfo; matches the `type` of the collection node. */
  type: string;
  /** A unique key for this LayoutInfo; matches the `key` of the collection node. */
  key: Key;
  /** The key for a parent LayoutInfo, if any. */
  parentKey: Key | null;
  /** Content for this item if it was generated by the layout rather than coming from the Collection. */
  content: any | null;
  /** The rectangle describing the size and position of this element. */
  rect: Rect;
  /** Whether the size is estimated (measured the first time the item is added to the DOM). Default false. */
  estimatedSize: boolean;
  /** Whether the layout info sticks to the viewport when scrolling. Default false. */
  isSticky: boolean;
  /** The element's opacity. Default 1. */
  opacity: number;
  /** A CSS transform string to apply to the element. `null` by default. */
  transform: string | null;
  /** The z-index of the element. 0 by default. */
  zIndex: number;
  /** Whether the element allows its contents to overflow its container. Default false. */
  allowOverflow: boolean;

  constructor(type: string, key: Key, rect: Rect) {
    this.type = type;
    this.key = key;
    this.parentKey = null;
    this.content = null;
    this.rect = rect;
    this.estimatedSize = false;
    this.isSticky = false;
    this.opacity = 1;
    this.transform = null;
    this.zIndex = 0;
    this.allowOverflow = false;
  }

  /** Returns a copy of the LayoutInfo. */
  copy(): LayoutInfo {
    const res = new LayoutInfo(this.type, this.key, this.rect.copy());
    res.estimatedSize = this.estimatedSize;
    res.opacity = this.opacity;
    res.transform = this.transform;
    res.parentKey = this.parentKey;
    res.content = this.content;
    res.isSticky = this.isSticky;
    res.zIndex = this.zIndex;
    res.allowOverflow = this.allowOverflow;
    return res;
  }
}
