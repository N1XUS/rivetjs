/** The strings of `locale` (cdk lookup: exact, language-script, language, any region, else en-US), `overrides` on top. */
export function schedulerStrings(locale: string, overrides?: Partial<SchedulerStrings>): SchedulerStrings {
  const table = getStringsForLocale(schedulerMessages as Record<string, Record<SchedulerMessageKey, string>>, locale) as SchedulerStrings;
  return overrides ? { ...table, ...overrides } : table;
}

/**
 * One message: `key` names a flat key (`"previous.week"`) or a plural base (`"moreEvents"`, variables need `count`):
 * the plural variant comes from `Intl.PluralRules(locale)` (cached), falling back to `.other`. `{name}` placeholders
 * are filled from `vars`.
 */
export function schedulerString(
  strings: SchedulerStrings,
  key: SchedulerMessageKey | "moreEvents" | "moreEventsLabel",
  vars: Record<string, string | number | boolean> | undefined,
  locale: string,
): string {
  let template = (strings as Record<string, string | undefined>)[key];
  if (template === undefined) {
    const category = cachedIntl(Intl.PluralRules, locale).select(Number(vars?.["count"] ?? 0));
    const table = strings as Record<string, string | undefined>;
    template = table[key + "." + category] ?? table[key + ".other"] ?? key;
  }
  return formatString(template, vars);
}
