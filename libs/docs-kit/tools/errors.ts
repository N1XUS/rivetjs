// Diagnostic code reference of a docs site (site config `errorPages: true`): `content/errors/index.md` (`/errors/`,
// every code by block + the reserved ranges) and one page per registered code `content/errors/RVxxxx.md`
// (`/errors/RVxxxx`, the URL every diagnostic links to: `docsUrl()` in libs/compiler/codes.ts). Built from the code
// registry (`libs/compiler/codes.json`: severity, title, retired, ranges, reserved) and the explanations
// (`libs/language-core/explain.json`: messages, fix, avoid / prefer, quick fix, note — the same text as the MCP
// `explain_diagnostic` tool), plus "See also" links to the content pages that mention the code. Committed Markdown
// (so check-content, llms and the MCP data read them like any page), rewritten by every prepare / build
// (`generateContent`), checked by `docs-kit errors <app> --check` (CI gates).
//   node libs/docs-kit/cli.ts errors apps/docs           # regenerate
//   node libs/docs-kit/cli.ts errors apps/docs --check   # no writes; fail on stale, missing or orphan pages
import { existsSync } from "node:fs";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { join, relative, resolve } from "node:path";
import { loadApp } from "./app.ts";
import { splitFrontmatter } from "./content/frontmatter.ts";

/** Content directory of the pages (`content/errors/`, route `/errors/`). */
export const ERRORS_DIR = "errors";
/** Registry + explanation files, relative to the repository root. */
export const ERROR_SOURCES = { codes: "libs/compiler/codes.json", explain: "libs/language-core/explain.json" } as const;

export interface RegistryCode {
  code: string;
  severity: "error" | "warning" | "info";
  title: string;
  retired?: boolean;
}
export interface Registry {
  /** Block prefix (`RV1`) → what the block covers. */
  ranges: Record<string, string>;
  reserved: { from: string; to: string; owner: string; title: string }[];
  codes: RegistryCode[];
}
export interface Explanation {
  code: string;
  /** Emitted texts (`{x}` = placeholder); `null` = no longer emitted. */
  messages: (string | null)[];
  fix: string;
  avoid?: string;
  prefer?: string;
  quickFix?: string;
  note?: string;
}
/** A content page that mentions a code. */
export interface Mention {
  path: string;
  title: string;
}

const HEADER = `# Generated by @rivetjs/docs-kit (tools/errors.ts) from ${ERROR_SOURCES.codes} + ${ERROR_SOURCES.explain}. Do not edit.`;
const CODE = /\bRV\d{4}\b/g;

/** Content path of a code's page (`errors/RV1016`). */
export const errorPagePath = (code: string): string => `${ERRORS_DIR}/${code}`;

/** Inline code span of `value` (a longer backtick fence when the code holds backticks). */
function codeSpan(value: string): string {
  const longest = Math.max(0, ...[...value.matchAll(/`+/g)].map((m) => m[0].length));
  const fence = "`".repeat(longest + 1);
  const pad = longest || value.startsWith("`") || value.endsWith("`") ? " " : "";
  return fence + pad + value + pad + fence;
}

/** Index after the bracket closing the one at `start` (`{}` / `()` / `<>` aware of nested braces), or -1. */
function closing(text: string, start: number): number {
  const open = text[start]!;
  const close = open === "{" ? "}" : open === "(" ? ")" : ">";
  let depth = 0;
  for (let i = start; i < text.length; i++) {
    const c = text[i]!;
    if (c === "`") {
      const end = text.indexOf("`", i + 1);
      if (end < 0) return -1;
      i = end;
      continue;
    }
    if (open === "<") {
      if (c === "{") {
        const end = closing(text, i);
        if (end < 0) return -1;
        i = end - 1;
        continue;
      }
      if (c === ">" && text[i - 1] !== "=") return i + 1;
      continue;
    }
    if (c === open) depth++;
    else if (c === close && --depth === 0) return i + 1;
  }
  return -1;
}

const IDENT = /[\w$@.:#-]/;

/**
 * Plain explanation text (explain.json prose: code written inline, some of it in backticks) → Markdown: JSX tags,
 * `{…}` expressions, calls `f(…)`, `a:b` attribute names and `_names` become code spans (adjacent pieces with no space
 * between them join into one span); the rest is escaped so it renders as written.
 */
export function proseMarkdown(input: string): string {
  const pieces: { code: boolean; text: string }[] = [];
  const push = (code: boolean, text: string) => {
    const last = pieces[pieces.length - 1];
    if (last && last.code === code) last.text += text;
    else pieces.push({ code, text });
  };
  let i = 0;
  while (i < input.length) {
    const c = input[i]!;
    if (c === "`") {
      const end = input.indexOf("`", i + 1);
      if (end > i + 1) {
        push(true, input.slice(i + 1, end));
        i = end + 1;
        continue;
      }
    }
    if (c === "{" || (c === "<" && /[A-Za-z/]/.test(input[i + 1] ?? ""))) {
      const end = closing(input, i);
      if (end > 0) {
        push(true, input.slice(i, end));
        i = end;
        continue;
      }
    }
    if (IDENT.test(c) && (i === 0 || !IDENT.test(input[i - 1]!))) {
      let end = i;
      while (end < input.length && IDENT.test(input[end]!)) end++;
      // Trailing sentence punctuation is prose.
      while (end > i && /[.:#-]/.test(input[end - 1]!)) end--;
      const word = input.slice(i, end);
      const next = input[end];
      if (word && (next === "(" || next === "<") && /[A-Za-z_$:]/.test(word[0]!)) {
        const close = closing(input, end);
        if (close > 0) {
          let stop = close;
          if (input[stop] === "(") stop = Math.max(stop, closing(input, stop));
          push(true, input.slice(i, stop));
          i = stop;
          continue;
        }
      }
      if (word && next === "=" && input[end + 1] === "{") {
        const close = closing(input, end + 1);
        if (close > 0) {
          push(true, input.slice(i, close));
          i = close;
          continue;
        }
      }
      if (/^_\w/.test(word) || /^[A-Za-z]\w*:[A-Za-z(]/.test(word)) {
        push(true, word);
        i = end;
        continue;
      }
      if (word) {
        push(false, word);
        i = end;
        continue;
      }
    }
    push(false, c);
    i++;
  }
  // Code joined by a gap without spaces (`<option>/<optgroup>`, `<tr><td>text</td></tr>`) is one span.
  const merged: { code: boolean; text: string }[] = [];
  for (const piece of pieces) {
    const prev = merged[merged.length - 1];
    const before = merged[merged.length - 2];
    if (piece.code && prev && !prev.code && before?.code && /^[^\s]+$/.test(prev.text) && !/[,;]$/.test(prev.text)) {
      merged.pop();
      before.text += prev.text + piece.text;
      continue;
    }
    merged.push({ ...piece });
  }
  return merged.map((piece) => (piece.code ? codeSpan(piece.text) : escapeProse(piece.text))).join("");
}

/** Markdown-escape plain text (emphasis, link brackets, HTML, entities, text directives, strike-through). */
function escapeProse(value: string): string {
  return (
    value
      .replace(/[\\*<~]/g, (c) => "\\" + c)
      // A bracket pair only links when `(` / `[` / `:` follows it; `[]` stays as written. Intraword `_` never emphasizes.
      .replace(/\[(?=[^\]]*\]\s*[([:])/g, "\\[")
      .replace(/&(?=#?\w+;)/g, "\\&")
      .replace(/(^|\s):(?=\w)/g, "$1\\:")
  );
}

/**
 * explain.json `quickFix` (`fixName: "Label"; other: "Label" → result (notes)`) → one Markdown line per code action:
 * the label as the editor shows it, then what it writes (the text after the last label).
 */
export function quickFixes(value: string): string[] {
  const actions: string[] = [];
  const label = /(\w+): "((?:[^"\\]|\\.)*)"/g;
  let end = 0;
  for (const match of value.matchAll(label)) {
    actions.push(proseMarkdown(JSON.parse(`"${match[2]}"`) as string));
    end = match.index + match[0].length;
  }
  if (!actions.length) return [proseMarkdown(value)];
  const tail = value.slice(end).replace(/^[;\s]+/, "");
  // `→ <code the action writes>` up to `; ` / ` (+`, then notes.
  const result = /^→\s*(.+?)(?=;\s|\s\(\+|$)(.*)$/.exec(tail);
  if (result) actions[actions.length - 1] += ` → ${codeSpan(result[1]!)}${proseMarkdown(result[2]!)}`;
  else if (tail) actions[actions.length - 1] += " " + proseMarkdown(tail);
  return actions;
}

/** A message placeholder: `{name}`, `{#field}`, `{…}`, `{an `if` | a loop}` (not an expression such as `{(el) => x}`). */
const PLACEHOLDER = /\{(?![(\s{])[^{}=]+\}/;

/** Frontmatter string value (JSON-quoted: the frontmatter parser reads double-quoted values as JSON). */
const quoted = (value: string): string => JSON.stringify(value);
const sentence = (value: string): string => value.charAt(0).toUpperCase() + value.slice(1);
const cell = (value: string): string => proseMarkdown(value).replace(/\|/g, "\\|");

/** Page description (≤ 160 characters, the frontmatter limit). */
function description(code: RegistryCode): string {
  const tail = code.retired ? " Retired: no longer reported." : " What triggers it and how to fix it.";
  const head = `Rivet diagnostic ${code.code} (${code.severity}): `;
  let title = code.title.replace(/\s+/g, " ");
  const room = 160 - head.length - tail.length - 1;
  if (title.length > room) title = title.slice(0, room - 1).trimEnd() + "…";
  return head + title + "." + tail;
}

/** Markdown of one code's page. */
export function errorPageMarkdown(code: RegistryCode, explanation: Explanation, registry: Registry, mentions: readonly Mention[]): string {
  const block = registry.ranges[code.code.slice(0, 3)];
  const lines = [
    "---",
    HEADER,
    `title: ${quoted(`${code.code}: ${code.title}`)}`,
    `description: ${quoted(description(code))}`,
    "template: reference",
    "tags: [diagnostics]",
    "---",
    "",
  ];
  const facts = [`**Severity:** ${code.severity}`];
  if (block) facts.push(`**Area:** ${proseMarkdown(sentence(block))} (\`${code.code.slice(0, 3)}xxx\`)`);
  facts.push(`**Quick fix:** ${explanation.quickFix ? "yes" : "none"}`);
  lines.push(facts.join(" · "), "");
  if (code.retired)
    lines.push(":::note[Retired]", "Rivet no longer reports this code. Codes are never reused, so this page stays for older logs and tools.", ":::", "");
  const messages = explanation.messages.filter((message): message is string => !!message);
  if (messages.length) {
    lines.push("## Message", "");
    lines.push(messages.length > 1 ? "The diagnostic reads one of:" : "The diagnostic reads:", "");
    for (const message of messages) lines.push("```text", message, "```", "");
    if (messages.some((message) => PLACEHOLDER.test(message))) lines.push("Parts in braces (`{name}`) are filled in for each report.", "");
  }
  lines.push(code.retired ? "## Status" : "## How to fix", "", proseMarkdown(explanation.fix), "");
  if (explanation.avoid || explanation.prefer) {
    lines.push("## Example", "");
    if (explanation.avoid) lines.push("```tsx avoid nocheck", explanation.avoid, "```", "");
    if (explanation.prefer) lines.push("```tsx prefer", explanation.prefer, "```", "");
  }
  if (explanation.quickFix) {
    const actions = quickFixes(explanation.quickFix);
    lines.push(
      "## Quick fix",
      "",
      `The [language service](../guides/tooling/language-service.md) (editor) and the MCP \`check_code\` tool offer ${actions.length > 1 ? "these code actions" : "this code action"}:`,
      "",
      ...actions.map((action) => `- ${action}`),
      "",
    );
  }
  if (explanation.note) lines.push("## When it is reported", "", proseMarkdown(explanation.note), "");
  lines.push("## See also", "");
  for (const mention of mentions) lines.push(`- [${cell(mention.title)}](../${mention.path}.md)`);
  lines.push("- [All diagnostic codes](index.md)", "");
  return lines.join("\n");
}

/** Markdown of the index page: every code by block, then the reserved ranges. */
export function errorIndexMarkdown(registry: Registry): string {
  const lines = [
    "---",
    HEADER,
    'title: "Diagnostic codes"',
    `description: ${quoted("Every RV code the Rivet compiler, Vite plugin and language service report: severity, title and a page with the fix.")}`,
    "template: reference",
    "tags: [diagnostics]",
    "---",
    "",
    "Every error, warning and hint from the Rivet compiler, the Vite plugin and the language service has a stable code such as `RV2001`. The `docs:` link printed with a diagnostic opens its page here: what the message means, how to fix it, a before / after pair and the quick fix your editor offers.",
    "",
    "Codes are never reused. A retired code keeps its page.",
    "",
  ];
  for (const [prefix, title] of Object.entries(registry.ranges)) {
    const codes = registry.codes.filter((code) => code.code.startsWith(prefix));
    if (!codes.length) continue;
    lines.push(`## ${prefix}xxx: ${proseMarkdown(sentence(title))}`, "", "| Code | Severity | Title |", "| --- | --- | --- |");
    for (const code of codes) lines.push(`| [${code.code}](${code.code}.md) | ${code.retired ? "retired" : code.severity} | ${cell(code.title)} |`);
    lines.push("");
  }
  if (registry.reserved.length) {
    lines.push("## Reserved ranges", "", "Other packages assign the codes in these ranges; they have no pages here yet.", "");
    lines.push("| Range | Package | Covers |", "| --- | --- | --- |");
    for (const range of registry.reserved) lines.push(`| \`${range.from}\`–\`${range.to}\` | \`${range.owner}\` | ${cell(range.title)} |`);
    lines.push("");
  }
  lines.push("## See also", "", "- [Language service](../guides/tooling/language-service.md): these diagnostics in the editor and in CI (`rivet-check`)", "");
  return lines.join("\n");
}

/** Every page (content path → Markdown) for a registry, its explanations and the mentions per code. */
export function renderErrorPages(
  registry: Registry,
  explanations: readonly Explanation[],
  mentions: ReadonlyMap<string, readonly Mention[]>,
): Map<string, string> {
  const byCode = new Map(explanations.map((entry) => [entry.code, entry]));
  const pages = new Map<string, string>([[`${ERRORS_DIR}/index`, errorIndexMarkdown(registry)]]);
  for (const code of registry.codes) {
    const explanation = byCode.get(code.code);
    if (!explanation) throw new Error(`${ERROR_SOURCES.explain}: no entry for ${code.code} (every code in ${ERROR_SOURCES.codes} needs one)`);
    pages.set(errorPagePath(code.code), errorPageMarkdown(code, explanation, registry, mentions.get(code.code) ?? []));
  }
  for (const entry of explanations)
    if (!registry.codes.some((code) => code.code === entry.code)) throw new Error(`${ERROR_SOURCES.explain}: ${entry.code} is not in ${ERROR_SOURCES.codes}`);
  return pages;
}

/** Content pages (outside `errors/`) that mention each code, in path order. */
async function findMentions(contentDir: string): Promise<Map<string, Mention[]>> {
  const mentions = new Map<string, Mention[]>();
  const entries = await readdir(contentDir, { recursive: true, withFileTypes: true });
  const files = entries
    .filter((entry) => entry.isFile() && entry.name.endsWith(".md") && !entry.name.startsWith("_"))
    .map((entry) => relative(contentDir, join(entry.parentPath, entry.name)).split("\\").join("/").replace(/\.md$/, ""))
    .filter((path) => !path.startsWith(ERRORS_DIR + "/"))
    .sort();
  for (const path of files) {
    const source = await readFile(resolve(contentDir, path + ".md"), "utf8");
    const codes = new Set(source.match(CODE) ?? []);
    if (!codes.size) continue;
    const title = splitFrontmatter(source, `content/${path}.md`).raw.title;
    for (const code of codes) {
      const list = mentions.get(code) ?? [];
      list.push({ path, title: typeof title === "string" ? title : path });
      mentions.set(code, list);
    }
  }
  return mentions;
}

/** Load the sources and render every page of the app at `root`. */
export async function errorPages(root: string): Promise<Map<string, string>> {
  const { repo } = await loadApp(root);
  const registry = JSON.parse(await readFile(resolve(repo, ERROR_SOURCES.codes), "utf8")) as Registry;
  const explain = JSON.parse(await readFile(resolve(repo, ERROR_SOURCES.explain), "utf8")) as { codes: Explanation[] };
  return renderErrorPages(registry, explain.codes, await findMentions(resolve(root, "content")));
}

/** Differences between the rendered pages and `content/errors/` (stale, missing, orphan files). */
export async function errorPageProblems(root: string, pages?: Map<string, string>): Promise<string[]> {
  pages ??= await errorPages(root);
  const dir = resolve(root, "content", ERRORS_DIR);
  const problems: string[] = [];
  for (const [path, markdown] of pages) {
    const file = resolve(root, "content", path + ".md");
    if (!existsSync(file)) problems.push(`content/${path}.md is missing`);
    else if ((await readFile(file, "utf8")) !== markdown) problems.push(`content/${path}.md is stale`);
  }
  if (existsSync(dir))
    for (const name of await readdir(dir))
      if (!pages.has(`${ERRORS_DIR}/${name.replace(/\.md$/, "")}`)) problems.push(`content/${ERRORS_DIR}/${name} has no code (orphan)`);
  return problems;
}

/** Write the pages of the app at `root` (only changed files; orphans removed). Returns the written / removed paths. */
export async function generateErrorPages(root: string): Promise<string[]> {
  const pages = await errorPages(root);
  const dir = resolve(root, "content", ERRORS_DIR);
  await mkdir(dir, { recursive: true });
  const written: string[] = [];
  for (const [path, markdown] of pages) {
    const file = resolve(root, "content", path + ".md");
    if (existsSync(file) && (await readFile(file, "utf8")) === markdown) continue;
    await writeFile(file, markdown);
    written.push(`content/${path}.md`);
  }
  for (const name of await readdir(dir))
    if (!pages.has(`${ERRORS_DIR}/${name.replace(/\.md$/, "")}`)) {
      await rm(resolve(dir, name), { recursive: true });
      written.push(`content/${ERRORS_DIR}/${name}`);
    }
  return written;
}

/** CLI: `docs-kit errors <app root> [--check]`. */
export async function errorsCommand(root: string, args: string[]): Promise<void> {
  const { site } = await loadApp(root);
  if (!site.errorPages) {
    console.error("docs-kit errors: this site has no error pages (site.config.ts errorPages: true)");
    process.exitCode = 2;
    return;
  }
  const pages = await errorPages(root);
  if (args.includes("--check")) {
    const problems = await errorPageProblems(root, pages);
    if (problems.length) {
      console.error(
        `errors --check: ${problems.length} problem(s) (run node libs/docs-kit/cli.ts errors ${relative(process.cwd(), root) || "."})\n  ${problems.join("\n  ")}`,
      );
      process.exitCode = 1;
      return;
    }
    console.log(`errors --check: ok, ${pages.size} pages`);
    return;
  }
  const written = await generateErrorPages(root);
  console.log(`errors: ${pages.size} pages, ${written.length} written${written.length ? "\n  " + written.join("\n  ") : ""}`);
}
