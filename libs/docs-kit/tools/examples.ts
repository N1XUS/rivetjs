const HEIGHTS = { xs: 96, sm: 180, md: 320, lg: 480, xl: 640 } as const;
const SKIP = /(^|\/)(node_modules|dist|\.rivet)(\/|$)|(^|\/)example\.ts$/;
const posix = (path: string) => path.split(sep).join("/");
const HEADER = (what: string) => `// Generated by @rivetjs/docs-kit/tools/examples.ts${what ? ` (${what})` : ""}. Do not edit.\n`;

async function listFiles(dir: string): Promise<string[]> {
  if (!existsSync(dir)) return [];
  const entries = await readdir(dir, { recursive: true, withFileTypes: true });
  return entries
    .filter((entry) => entry.isFile())
    .map((entry) => posix(relative(dir, join(entry.parentPath, entry.name))))
    .filter((file) => !SKIP.test(file))
    .sort();
}

/** Example ids of the app at `root` (folders with an example.ts; `_` folders are shared files). */
export async function exampleIds(root: string): Promise<string[]> {
  const dir = resolve(root, "examples");
  if (!existsSync(dir)) return [];
  const entries = await readdir(dir, { withFileTypes: true });
  return entries
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith("_") && existsSync(join(dir, entry.name, "example.ts")))
    .map((entry) => entry.name)
    .sort();
}

/** `example.ts` of `id` (re-imported after an edit: the mtime busts the ESM cache). */
export async function loadExample(root: string, id: string): Promise<ExampleConfig> {
  const file = resolve(root, "examples", id, "example.ts");
  const { mtimeMs } = await stat(file);
  return ((await import(pathToFileURL(file).href + "?t=" + mtimeMs)) as { default: ExampleConfig }).default;
}

/** Strip `// #region demo` markers; return the shown text and the focus range (1-based lines). */
export function focusRegion(source: string): { text: string; focus?: [number, number] } {
  const lines = source.split("\n");
  const kept: string[] = [];
  let start: number | undefined, end: number | undefined;
  for (const line of lines) {
    if (/^\s*(\/\/|\{\/\*)\s*#region\b/.test(line)) {
      start = kept.length + 1;
      continue;
    }
    if (/^\s*(\/\/|\{\/\*)\s*#endregion\b/.test(line)) {
      end = kept.length;
      continue;
    }
    kept.push(line);
  }
  const text = kept.join("\n").replace(/\n+$/, "\n");
  return start !== undefined && end !== undefined && end >= start ? { text, focus: [start, end] } : { text };
}

/** A shown file: plain text (`#region` markers and line notation stripped) + marks + focus; the browser colours it. */
export function shownFile(path: string, source: string): ExampleFile {
  const { text, focus } = focusRegion(source);
  const lines = codeLines(text);
  const marks: Record<number, "highlight" | "add" | "remove"> = {};
  lines.forEach((line, index) => {
    if (line.mark) marks[index + 1] = line.mark;
  });
  return {
    path,
    text: lines.map((line) => line.text).join("\n") + "\n",
    ...(Object.keys(marks).length ? { marks } : {}),
    ...(focus ? { focus } : {}),
  };
}

// ---- Which examples run as pages of the docs app ----

/** Files that make an example its own app (a docs page cannot be built with them). */
const OWN_APP = /^(vite\.config\.ts|package\.json|prerender\.js|serve\.js|i18n\.config\.ts|src\/document\.ts|locales\/)/;
const PAGE = /\.(tsx|jsx)$/;
const SPECIAL = /(^|\/)_(404|error)\.(tsx|jsx)$/;
const LAYOUT = /(^|\/)_layout\.(tsx|jsx)$/;
/** Links that leave the frame: absolute app paths (`href="/x"`, `withBase(…)`, `navigate("/x")`). */
const ABSOLUTE_LINK = /\bhref=(?:"\/(?!\/)|\{\s*["'`]\/(?!\/))|\bwithBase\(|\bnavigate\(\s*["'`]\//;

// A layout's server export: `export const x = load(…)` (any `@rivetjs/router` server-export wrapper).
const SERVER_CODE = /^\s*export\s+const\s+[\w$]+\s*=\s*(?:load|guard|actions|entries|headers|on(?:Request|Get|Post|Put|Patch|Delete|Options))\s*\(/m;

/** A live example's page routes: frame sub-path ("" = the example's `/`) → route file, plus the layout chain of each. */
export interface FramePages {
  pages: { path: string; file: string; layouts: string[] }[];
}

/**
 * Why `id` cannot run as a page of the static docs app (shown as code only), or its pages. Static examples whose pages
 * are static paths (no params), linked relatively, with layouts and route groups, run live; in-file `load(…)` /
 * `prerender` of a static example runs when the docs are prerendered, as in the example's own static build.
 */
export function framePlan(config: ExampleConfig, files: readonly string[], sources: ReadonlyMap<string, string>): FramePages | { codeOnly: string } {
  if (config.mode === "server") return { codeOnly: "it needs a server (form actions, guards or cookies)" };
  const own = files.find((file) => OWN_APP.test(file));
  if (own)
    return { codeOnly: `it is its own app (${own.replace(/\/$/, "")}: ${own.startsWith("locales") || own.startsWith("i18n") ? "i18n" : "own build setup"})` };
  if (config.frame?.theme === false) return { codeOnly: "it manages its own theme" };
  const routes = files.filter((file) => file.startsWith("src/routes/")).map((file) => file.slice("src/routes/".length));
  if (routes.some((file) => /\.server\.[cm]?[jt]s$/.test(file) || (/\.[cm]?[jt]s$/.test(file) && !PAGE.test(file))))
    return { codeOnly: "it has server routes (endpoints or server modules)" };
  if (routes.some((file) => SPECIAL.test(file))) return { codeOnly: "it has its own 404 or error page" };
  const pages: FramePages["pages"] = [];
  for (const file of routes) {
    if (!PAGE.test(file) || LAYOUT.test(file) || /(^|\/)_/.test(file)) continue;
    const segments = file.replace(PAGE, "").split("/");
    if (segments.some((segment) => segment.startsWith("["))) return { codeOnly: "it has dynamic pages ([param] routes)" };
    const path = segments
      .filter((segment) => !/^\(.+\)$/.test(segment))
      .filter((segment, index, all) => !(segment === "index" && index === all.length - 1))
      .join("/");
    // Layouts: `_layout` of each folder from the routes root down to the page's folder.
    const folders = segments.slice(0, -1);
    const layouts: string[] = [];
    for (let depth = 0; depth <= folders.length; depth++) {
      const folder = folders.slice(0, depth).join("/");
      const layout = routes.find((route) => LAYOUT.test(route) && posix(dirname(route)) === (folder || "."));
      if (layout) layouts.push(layout);
    }
    pages.push({ path, file, layouts });
  }
  if (!pages.some((page) => page.path === "")) return { codeOnly: "it has no page at /" };
  for (const file of routes)
    if (LAYOUT.test(file) && SERVER_CODE.test(sources.get("src/routes/" + file) ?? "")) return { codeOnly: `its layout runs server code (${file})` };
  if (pages.length > 1)
    for (const [file, source] of sources)
      if (file.startsWith("src/") && ABSOLUTE_LINK.test(source)) return { codeOnly: `its pages link with absolute paths (${file})` };
  return { pages: pages.sort((a, b) => (a.path < b.path ? -1 : 1)) };
}

// ---- Stylesheets ----

/** The stylesheet text of an example: its own `src/styles.css`, else the static starter's. */
async function stylesOf(root: string, templates: string, id: string): Promise<string> {
  const own = resolve(root, "examples", id, "src/styles.css");
  return readFile(existsSync(own) ? own : resolve(templates, "starter-static/src/styles.css"), "utf8");
}

const SOURCE_LINE = /^@source\s+(["'])(\.{1,2}\/[^"']*)\1\s*;\s*$/gm;
const TAILWIND_IMPORT = /^@import\s+(["'])tailwindcss\1\s*;/m;

/**
 * One group stylesheet for the examples sharing `text`: relative `@source` lines repeated for every member (paths
 * from the generated file to `examples/<id>/src/`), and Tailwind's automatic source detection off (it would scan the
 * whole docs app; an example's own build scanned only the example). Relative `@import` / `url()` are rejected.
 */
export function groupCSS(text: string, members: readonly string[], fromGenerated: (id: string) => string): string {
  if (/@import\s+["']\.|url\(\s*["']?\.{1,2}\//.test(text))
    throw new Error("example styles.css: relative @import / url() is not supported (use a package import or an asset import)");
  let out = text.replace(TAILWIND_IMPORT, (line) => line.replace(/;$/, " source(none);"));
  out = out.replace(SOURCE_LINE, (_line, _quote: string, path: string) => members.map((id) => `@source "${posix(join(fromGenerated(id), path))}";`).join("\n"));
  return out;
}

