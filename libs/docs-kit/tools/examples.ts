// Examples are part of the docs app itself: each `examples/<id>/` holds a small app's sources (routes, components,
// styles.css), and the docs app imports them as ordinary modules of its own Vite graph. `generateExamples` writes:
// - `src/generated/examples.json`: what the <Example> component and the example pages show (meta, plain code),
//   read from disk on the server (`virtual:docs/examples`), never bundled;
// - `src/generated/example-frames/<id>.tsx` (live examples): the example's pages composed with its layouts, plus its
//   stylesheet import (route-scoped: linked only on that example's frame page);
// - `src/generated/example-frames.tsx`: id → page paths + lazy import of that wrapper, read by the frame route
//   `/examples/<id>/frame/[...path]` (`routes/examples/[id]/frame/[...path].tsx`, one dynamic route for all);
// - `src/generated/example-css/<hash>.css`: one stylesheet per distinct `styles.css` text, its `@source` lines
//   pointing at every example that shares it (Tailwind compiles once per group, not once per example).
// Examples that cannot run as a page of the static docs app (server mode, own config / document / i18n, endpoints,
// dynamic pages, absolute links between pages) are shown as code only (`ExampleData.codeOnly` says why).
