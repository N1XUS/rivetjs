/** Named exports of a module's source (route modules: `default`, `head`, `loader`, …). */
export function exportNames(source: string): string[] {
  const names = new Set<string>();
  for (const match of source.matchAll(/^\s*export\s+(?:declare\s+)?(?:const|let|var|async\s+function\*?|function\*?|class)\s+([A-Za-z_$][\w$]*)/gm))
    names.add(match[1]!);
  if (/^\s*export\s+default\b/m.test(source)) names.add("default");
  for (const match of source.matchAll(/^\s*export\s*\{([^}]*)\}/gm))
    for (const part of match[1]!.split(",")) {
      const name = part
        .trim()
        .split(/\s+as\s+/)
        .pop()
        ?.trim();
      if (name && !name.startsWith("type ")) names.add(name);
    }
  return [...names];
}

export interface GenerateResult {
  examples: Record<string, ExampleData>;
  /** Generated files written (app-relative); unchanged files are not rewritten. */
  written: string[];
}

/** Write `contents` when it differs (no mtime churn: Vite and the router watch these files). */
async function put(file: string, contents: string): Promise<boolean> {
  const current = await readFile(file, "utf8").catch(() => null);
  if (current === contents) return false;
  await mkdir(dirname(file), { recursive: true });
  await writeAtomic(file, contents);
  return true;
}

/** Content pages that embed each example (`::example{id=…}`). */
export async function usage(root: string): Promise<Map<string, { title: string; href: string }[]>> {
  const content = resolve(root, "content");
  const used = new Map<string, { title: string; href: string }[]>();
  for (const file of await listFiles(content)) {
    if (!file.endsWith(".md") || file.startsWith("_")) continue;
    const source = await readFile(resolve(content, file), "utf8");
    const title = /^title:\s*"?(.*?)"?\s*$/m.exec(source)?.[1] ?? file;
    const href = "/" + file.replace(/\.md$/, "").replace(/(^|\/)index$/, "") + "/";
    for (const match of source.matchAll(/::example\{[^}]*\bid="?([\w-]+)"?/g)) {
      const list = used.get(match[1]!) ?? [];
      if (!list.some((entry) => entry.href === href)) list.push({ title, href });
      used.set(match[1]!, list);
    }
  }
  return used;
}

/**
 * Describe every example of the app at `root` and write the generated files the docs app builds them from (see the
 * file header). `lenient`: problems of one example are reported and the example left out, instead of thrown (dev).
 */
export async function generateExamples(root: string, options: { lenient?: (message: string) => void } = {}): Promise<GenerateResult> {
  const app = await loadApp(root);
  const ids = await exampleIds(root);
  const used = await usage(root);
  const examples: Record<string, ExampleData> = {};
  const frames: { id: string; pages: FramePages["pages"] }[] = [];
  const groups = new Map<string, { text: string; members: string[] }>();
  for (const id of ids) {
    try {
      const dir = resolve(root, "examples", id);
      const config = await loadExample(root, id);
      const files = await listFiles(dir);
      const sources = new Map<string, string>();
      for (const file of files) if (/\.(tsx?|jsx?|css|md|json|html)$/.test(file)) sources.set(file, await readFile(resolve(dir, file), "utf8"));
      for (const file of config.show) if (!sources.has(file)) throw new Error(`example ${id}: show lists ${file}, which does not exist or is binary`);
      const plan = framePlan(config, files, sources);
      const height = typeof config.frame?.height === "number" ? config.frame.height : HEIGHTS[config.frame?.height ?? "sm"];
      examples[id] = {
        id,
        title: config.title,
        summary: config.summary,
        tags: config.tags ?? [],
        status: config.status ?? "stable",
        height,
        ...(config.frame?.auto ? { auto: true as const } : {}),
        phone: config.frame?.width === "phone",
        ...("codeOnly" in plan ? { codeOnly: plan.codeOnly } : { pages: plan.pages.map((page) => page.path) }),
        files: config.show.map((file) => shownFile(file, sources.get(file)!)),
        ...(config.test?.length ? { test: config.test } : {}),
        usedOn: used.get(id) ?? [],
      };
      if ("codeOnly" in plan) continue;
      frames.push({ id, pages: plan.pages });
      const text = await stylesOf(root, app.templates, id);
      const key = createHash("sha256").update(text).digest("hex").slice(0, 10);
      const group = groups.get(key) ?? { text, members: [] };
      group.members.push(id);
      groups.set(key, group);
    } catch (error) {
      if (!options.lenient) throw error;
      options.lenient(`example ${id}: ${(error as Error).message} — left out`);
    }
  }
  const written: string[] = [];
  const write = async (file: string, contents: string) => {
    if (await put(resolve(root, file), contents)) written.push(file);
  };
  // Stylesheets: one per group.
  const cssDir = resolve(root, CSS_DIR);
  const groupOf = new Map<string, string>();
  for (const [key, { text, members }] of groups) {
    for (const id of members) groupOf.set(id, key);
    const fromGenerated = (id: string) => posix(relative(cssDir, resolve(root, "examples", id, "src")));
    await write(
      `${CSS_DIR}/${key}.css`,
      `/* Generated by @rivetjs/docs-kit/tools/examples.ts (styles.css of ${members.length} example(s)). Do not edit. */\n` +
        groupCSS(text, members, fromGenerated),
    );
  }
  // Frame wrappers: the example's pages, each wrapped in its layouts, behind one module per example.
  const framesDir = resolve(root, FRAMES_DIR);
  const shells: string[] = [];
  for (const { id, pages } of frames) {
    const spec = (file: string) => posix(relative(framesDir, resolve(root, "examples", id, "src/routes", file)));
    // Per route file: its default export (the component) and the module (head, loader).
    const imports = new Map<string, number>();
    // `module` (head, loader) is read on the server only: named imports behind `import.meta.env.SSR`, so the browser
    // bundle keeps no namespace object (rolldown's `__exportAll` helper = one extra request per frame, UI-JS2).
    const names = new Map<number, readonly string[] | null>();
    const moduleOf = (index: number) => {
      const exported = names.get(index);
      if (exported === null) return `M${index}`;
      return `import.meta.env.SSR ? { ${exported!.map((name) => `${JSON.stringify(name)}: M${index}_${name}`).join(", ")} } : {}`;
    };
    const local = (file: string) => {
      let index = imports.get(file);
      if (index === undefined) {
        imports.set(file, (index = imports.size));
        const route = resolve(root, "examples", id, "src/routes", file);
        names.set(index, existsSync(route) ? namedExports(readFileSync(route, "utf8"), route) : null);
      }
      return index;
    };
    const entries = pages.map(({ path, file, layouts }) => {
      const page = local(file);
      // Router props as the example's own app gives them: layouts get accessors, the page plain values; the example's
      // pages have no params (static paths) and their own URL is the frame URL.
      const wrapped = layouts.reduceRight(
        (inner, layout) => `<C${local(layout)} data={() => undefined} params={() => ({})} url={() => props.url}>${inner}</C${local(layout)}>`,
        `<C${page} data={props.data} params={{}} url={props.url} />`,
      );
      // `props`: the frame root carries the route payload only when something reads it (a layout, a page with a parameter).
      const props = layouts.length ? "true" : `C${page}.length > 0`;
      if (!layouts.length) {
        const route = resolve(root, "examples", id, "src/routes", file);
        const facts = existsSync(route) ? moduleFacts(readFileSync(route, "utf8"), route, { boundaries: true }) : null;
        if (facts?.boundaries.get(facts.defaultName ?? "default")?.params === "none") shells.push(posix(relative(root, route)));
      }
      return `  ${JSON.stringify(path)}: { module: ${moduleOf(page)}, Page: (props: FrameProps) => ${wrapped}, props: ${props} },`;
    });
    const source = [
      HEADER(`examples/${id}`).trimEnd(),
      `import "../example-css/${groupOf.get(id)}.css";`,
      `import type { FrameComponent, FrameModule, FrameProps } from "@rivetjs/docs-kit/components/frame.tsx";`,
      ...[...imports].flatMap(([file, index]) => [
        names.get(index) === null
          ? `import _C${index}, * as M${index} from ${JSON.stringify(spec(file))};`
          : `import _C${index}${
              names.get(index)!.length
                ? `, { ${names
                    .get(index)!
                    .map((name) => `${name} as M${index}_${name}`)
                    .join(", ")} }`
                : ""
            } from ${JSON.stringify(spec(file))};`,
        // Pages / layouts that take no props (or typed ones): the frame passes router-shaped props to all.
        `const C${index} = _C${index} as FrameComponent;`,
      ]),
      "",
      "/** The example's pages by frame sub-path, each inside its layouts. */",
      'export const pages: FrameModule["pages"] = {',
      ...entries,
      "};",
      "",
    ].join("\n");
    await write(`${FRAMES_DIR}/${id}.tsx`, source);
  }
  await write(
    FRAMES_INDEX,
    [
      HEADER("example frames").trimEnd(),
      'import type { FrameModule } from "@rivetjs/docs-kit/components/frame.tsx";',
      "",
      "/** Live examples: id → their frame module (loaded on the server when the frame page renders). */",
      "export const frames: Record<string, { paths: readonly string[]; load: () => Promise<FrameModule> }> = {",
      ...frames.map(
        ({ id, pages }) =>
          `  ${JSON.stringify(id)}: { paths: ${JSON.stringify(pages.map((page) => page.path))}, load: () => import(${JSON.stringify("./example-frames/" + id + ".tsx")}) },`,
      ),
      "};",
      "",
    ].join("\n"),
  );
  await write(EXAMPLES_JSON, JSON.stringify(examples) + "\n");
  await write(FRAME_SHELLS, JSON.stringify(shells.sort()) + "\n");
  // Stale wrappers / stylesheets of removed examples.
  for (const [dir, keep] of [
    [framesDir, new Set(frames.map(({ id }) => id + ".tsx"))],
    [cssDir, new Set([...groups.keys()].map((key) => key + ".css"))],
  ] as const)
    if (existsSync(dir))
      for (const name of await readdir(dir))
        if (!keep.has(name)) {
          await rm(resolve(dir, name), { force: true });
          written.push(posix(relative(root, resolve(dir, name))));
        }
  // Outputs of the old pipeline (per-example builds): typed data module + per-example data, now `EXAMPLES_JSON`.
  for (const legacy of LEGACY_OUTPUTS)
    if (existsSync(resolve(root, legacy))) {
      await rm(resolve(root, legacy), { recursive: true, force: true });
      written.push(legacy);
    }
  return { examples, written };
}

/** Generated files of the removed per-example build pipeline, deleted on the next generation. */
const LEGACY_OUTPUTS = ["src/generated/examples.ts", "src/generated/examples"];

/** CLI: `docs-kit examples <app root>`: regenerate and list the code-only examples with the reason. */
export async function examplesCommand(root: string): Promise<void> {
  const { examples, written } = await generateExamples(root);
  const all = Object.values(examples);
  const codeOnly = all.filter((example) => example.codeOnly);
  console.log(`examples: ${all.length} (${all.length - codeOnly.length} live, ${codeOnly.length} code only), ${written.length} file(s) written`);
  for (const example of codeOnly) console.log(`  code only: ${example.id} — ${example.codeOnly}`);
}

/**
 * Route data exports of a route module (`head` in any form, the `load(…)` loader, other non-function values, `export { a, b as c }`;
 * not function / class declarations = components), or null when the module has a form this does not read (`export *`,
 * re-exports, destructuring): the frame then keeps the namespace import.
 */
const FUNCTION_VALUE = new Set(["ArrowFunctionExpression", "FunctionExpression", "ClassExpression"]);

function namedExports(code: string, file: string): readonly string[] | null {
  type Node = { type: string; [key: string]: unknown };
  let program: { body: Node[] };
  try {
    program = parseAst(code, { lang: file.endsWith(".tsx") ? "tsx" : file.endsWith(".ts") ? "ts" : "jsx" }) as unknown as { body: Node[] };
  } catch {
    return null;
  }
  const names = new Set<string>();
  // Top-level function / class bindings (components): `export { Demo }` skips them too.
  const functions = new Set<string>();
  for (const node of program.body) {
    const declaration = (node.type === "ExportNamedDeclaration" ? node.declaration : node) as Node | null;
    if (declaration?.type === "FunctionDeclaration" || declaration?.type === "ClassDeclaration") functions.add((declaration.id as Node).name as string);
    else if (declaration?.type === "VariableDeclaration")
      for (const declarator of declaration.declarations as Node[])
        if ((declarator.id as Node).type === "Identifier" && FUNCTION_VALUE.has((declarator.init as Node | null)?.type ?? ""))
          functions.add((declarator.id as Node).name as string);
  }
  for (const node of program.body) {
    if (node.type === "ExportAllDeclaration") return null;
    if (node.type !== "ExportNamedDeclaration" || node.exportKind === "type") continue;
    if (node.source) return null;
    const declaration = node.declaration as Node | null;
    if (declaration) {
      if (declaration.type === "VariableDeclaration") {
        for (const declarator of declaration.declarations as Node[]) {
          const id = declarator.id as Node;
          if (id.type !== "Identifier") return null;
          // Components (function values) are no route data: referencing them as values here would make the analysis
          // treat them as escaping (no site records).
          if (id.name === "head" || !FUNCTION_VALUE.has((declarator.init as Node | null)?.type ?? "")) names.add(id.name as string);
        }
      } else if (declaration.type === "TSEnumDeclaration" && !(declaration as { declare?: boolean }).declare)
        names.add((declaration.id as Node).name as string);
      else if (declaration.type === "FunctionDeclaration" && (declaration.id as Node).name === "head") names.add("head");
      continue;
    }
    for (const specifier of node.specifiers as Node[]) {
      if (specifier.exportKind === "type") continue;
      const exported = specifier.exported as Node;
      const name = (exported.name ?? exported.value) as string;
      if (name === "default" || (name !== "head" && functions.has(((specifier.local as Node).name ?? "") as string))) continue;
      if (!/^[A-Za-z_$][\w$]*$/.test(name)) return null;
      names.add(name);
    }
  }
  return [...names].sort();
}
