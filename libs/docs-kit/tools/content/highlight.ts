// Code at build time: plain lines (line notation `// [!code highlight|++|--]` stripped into marks); pages get no
// tokens (fragments do: generate.ts `loadTokenizer`, coloured blocks carry `data-hl`). The build colours page blocks after prerender (../highlight-pages.ts); the browser (../../components/highlighter.ts, one lazy shared chunk) colours dev pages and runtime-filled blocks; this module writes the
// colour classes' rules (`src/generated/highlight.css`) from the two themes' palettes.
import githubDark from "shiki/themes/github-dark.mjs";
import githubLight from "shiki/themes/github-light.mjs";
import { AA_COLORS, darkClass, lightClass, STYLE_CLASSES } from "../../components/highlight-classes.ts";

export { AA_COLORS, LANGS } from "../../components/highlight-classes.ts";

/** One line of a code block and its line notation mark. */
export interface Line {
  text: string;
  mark?: "highlight" | "add" | "remove";
}

export interface Highlight {
  /** Lines of `code` with line notation stripped into marks (`lang` is accepted for symmetry; not used). */
  lines(code: string, lang?: string): Line[];
  /** CSS for every token colour of both themes (light, dark via `[data-theme=dark]`) and the font styles. */
  css(): string;
}

const NOTATION = /\s*(?:\/\/|#|<!--|\/\*)\s*\[!code (highlight|\+\+|--)\]\s*(?:-->|\*\/)?\s*$/;

/** Plain lines of `code` (trailing newline dropped), notation stripped. */
export function codeLines(code: string): Line[] {
  return code
    .replace(/\n$/, "")
    .split("\n")
    .map((line) => {
      const found = NOTATION.exec(line);
      if (!found) return { text: line };
      return { text: line.slice(0, found.index), mark: found[1] === "++" ? "add" : found[1] === "--" ? "remove" : "highlight" };
    });
}

type ThemeJSON = { colors?: Record<string, string>; tokenColors?: { settings?: { foreground?: string } }[] };
/** Every foreground colour a theme can give a token (its default foreground included), lower case. */
export function palette(theme: ThemeJSON): string[] {
  const colors = [theme.colors?.["editor.foreground"], ...(theme.tokenColors ?? []).map((rule) => rule.settings?.foreground)];
  return [...new Set(colors.filter((color): color is string => !!color).map((color) => color.toLowerCase()))].sort();
}

/** The theme stylesheet (same for every site). */
export function highlightCSS(): string {
  const rules = [
    ...palette(githubLight as ThemeJSON).map((color) => `.${lightClass(color)}{color:${AA_COLORS.light[color] ?? color}}`),
    ...palette(githubDark as ThemeJSON).map((color) => `[data-theme=dark] .${darkClass(color)}{color:${AA_COLORS.dark[color] ?? color}}`),
    ...STYLE_CLASSES.map(([, name, rule]) => `.${name}{${rule}}`),
  ];
  return (
    "/* Generated by @rivetjs/docs-kit (Shiki github-light / github-dark palettes; tokens coloured at build or in the browser). */\n" + rules.join("\n") + "\n"
  );
}

/** Build-side code helper (sync work; async for API stability). */
export async function createHighlight(): Promise<Highlight> {
  return { lines: (code) => codeLines(code), css: highlightCSS };
}
