// Vite client + server build of a docs app in a child process. Rolldown's native memory and the JS heap of the
// module graph (~1.9 GB for cdk-docs / ui-docs) are not given back to the OS after `buildApp()` in the same process,
// so prerender and the Chromium example checks used to run on top of them (3.2 / 3.4 GB peak tree RSS, over the
// 3 GB budget). The child exits when the build is done: its memory is gone before the next phase starts. Client and
// server bundles build in two children, one after the other (as an app's `vite build && vite build --ssr`: the server
// reads the client's manifests from disk): one process holding both graphs peaked ~0.2–0.4 GB higher. Its V8 heap
// is capped (`VITE_HEAP_MB`): the build's live heap peaks at ~0.57 GB (ui-docs client, cold compile cache, end of the
// bundle's generate phase; 2026-10-29), and a looser cap only lets garbage stay resident (1536 MB: +0.29 GB peak RSS,
// same wall time; uncapped ≈ 4 GB on a 48 GB host). Rolldown's own (mimalloc) memory is ~1.1 GB of the child's peak;
// its thread pools are capped too (`VITE_THREADS`): every worker thread keeps its own heap pages (−0.1 GB at 4 vs 14
// threads, same wall time; UIDOCS-RSS 2026-10-29).
import { spawn } from "node:child_process";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

export interface ViteBuildOptions {
  /** Output: `<dist>/client` + `<dist>/server`. */
  dist: string;
  /** Record the module graph into `.artifacts/site-graph.json` (`graph.ts`). */
  graph?: boolean;
  /** Extra environment for the child (e.g. the frames-only switch of `check-examples`). */
  env?: Record<string, string>;
  /** Build only the client bundle (co-load pass 2, `coload.ts`: the server bundle reads the client's files at run time). */
  clientOnly?: boolean;
}

/** V8 old-space cap of the build child in MB (env `DOCS_KIT_VITE_HEAP_MB` overrides). */
export const VITE_HEAP_MB = 768;
/**
 * Rolldown worker threads of the build child (tokio `ROLLDOWN_WORKER_THREADS` + rayon `RAYON_NUM_THREADS`; either env
 * set by the caller wins).
 */
export const VITE_THREADS = 4;

/** Env set for the server-bundle child: content + example frames were generated by the client child (`content/plugin.ts`). */
export const GENERATED_ENV = "DOCS_KIT_GENERATED";

type Environment = "client" | "ssr";
interface ChildOptions {
  dist: string;
  graph: boolean;
  environment: Environment;
}

/** Run the docs app's Vite build (client, then server bundle) in child processes (stdio inherited); rejects when one fails. */
export async function viteBuild(root: string, options: ViteBuildOptions): Promise<void> {
  await child(root, { dist: options.dist, graph: !!options.graph, environment: "client" }, options.env);
  if (!options.clientOnly) await child(root, { dist: options.dist, graph: !!options.graph, environment: "ssr" }, { ...options.env, [GENERATED_ENV]: "1" });
}

function child(root: string, options: ChildOptions, env: Record<string, string> | undefined): Promise<void> {
  const heap = Number(process.env.DOCS_KIT_VITE_HEAP_MB) || VITE_HEAP_MB;
  const args = [...process.execArgv, `--max-old-space-size=${heap}`, fileURLToPath(import.meta.url), resolve(root), JSON.stringify(options)];
  return new Promise((done, fail) => {
    const threads = String(VITE_THREADS);
    const child = spawn(process.execPath, args, {
      stdio: "inherit",
      env: { ROLLDOWN_WORKER_THREADS: threads, RAYON_NUM_THREADS: threads, ...process.env, ...env },
    });
    const stop = () => child.kill();
    process.once("exit", stop);
    child.once("error", fail);
    child.once("exit", (code, signal) => {
      process.off("exit", stop);
      if (code === 0) done();
      else fail(new Error(`docs-kit: Vite ${options.environment} build of ${root} failed (${signal ? "signal " + signal : "exit code " + code})`));
    });
  });
}

/** One environment's build (child side). The server child adds its modules to the graph the client child wrote. */
async function run(root: string, options: ChildOptions): Promise<void> {
  const { createBuilder } = await import("vite");
  const { loadApp } = await import("./app.ts");
  const { graphPlugin, readGraph, siteGraphFile, writeGraph } = await import("./graph.ts");
  const { repo } = await loadApp(root);
  const graph = options.graph && options.environment === "ssr" ? ((await readGraph(siteGraphFile(root))) ?? new Set<string>()) : new Set<string>();
  const builder = await createBuilder({
    root,
    configFile: resolve(root, "vite.config.ts"),
    ...(options.graph ? { plugins: [graphPlugin(repo, graph)] } : {}),
    builder: {},
    build: { minify: true },
    environments: {
      client: { build: { outDir: resolve(options.dist, "client") } },
      ssr: { build: { outDir: resolve(options.dist, "server"), manifest: false, rollupOptions: { input: resolve(root, ".rivet/entry.server.tsx") } } },
    },
  });
  await builder.build(builder.environments[options.environment]!);
  if (options.graph) await writeGraph(siteGraphFile(root), graph);
}

if (import.meta.main) {
  run(process.argv[2]!, JSON.parse(process.argv[3]!) as ChildOptions).then(
    // Exit at once: open handles (watchers, workers) would keep the memory alive.
    () => process.exit(0),
    (error: unknown) => {
      console.error(error);
      process.exit(1);
    },
  );
}
