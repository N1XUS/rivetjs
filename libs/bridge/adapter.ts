// @rivetjs/bridge/adapter — the contract between the bridge core and one framework adapter (`@rivetjs/bridge-<fw>`).
// Spec docs/design/specs/2026-10-11-framework-bridges-design.md §3.2. Types, the identity `defineAdapter`, and
// `islandRecovered` (RV2149, the adapters' report of a hydration recovery).
import type { ServerValue } from "@rivetjs/runtime/server";
import { DEV } from "#dev";

/** Placeholder where Rivet content goes in the framework's HTML: `<rivet-slot [name="x"] style="display:contents"></rivet-slot>`. */
export interface SlotMark {
  /** Slot name: `"default"` for `children`, else the content prop's key. */
  readonly name: string;
  /** The exact markup the adapter must render for the hole (an empty element; the bridge writes the content into it). */
  readonly html: string;
}

/** Per-island server render context. */
export interface IslandContext {
  /** Per-request island id (`"i3"`); adapters use it as the framework's id prefix (React `identifierPrefix`). */
  readonly id: string;
  /** CSP nonce of the Rivet render (React / Solid inline scripts); `undefined` when the render has none. */
  readonly nonce: string | undefined;
  /** Request abort (created on first read). */
  readonly signal: AbortSignal;
  /** The hole of slot `name` (same object as `slots[name]`). */
  slot(name: string): SlotMark;
}

/** Head entries an island render hoists (React 19 `<title>` / `<meta>` / `<link>`, Svelte `head`, Vue head teleports). */
export type IslandHead = Record<string, unknown>;

/** A render with hoisted head entries (forwarded to the app's head sink, `IslandDef.head`). */
export interface IslandRender {
  readonly html: string;
  readonly head?: IslandHead;
}

export interface ServerAdapter<C = unknown> {
  name: "react" | "preact" | "vue" | "svelte" | "solid" | (string & {});
  /** HTML of the island's content (no wrapper), with one `SlotMark.html` per slot. Sync when the framework can; a Promise otherwise. */
  render(
    component: C,
    props: Record<string, unknown>,
    slots: Record<string, SlotMark>,
    ctx: IslandContext,
  ): string | IslandRender | PromiseLike<string | IslandRender>;
  /** Once per page (per id scope), before the first island of this adapter (Solid `_$HY` script). Optional. */
  head?(ctx: IslandContext): string;
}

export interface ClientAdapter<C = unknown, H = unknown> {
  hydrate(root: Element, component: C, props: Record<string, unknown>, slots: Record<string, Node[] | null>, ctx: { id: string }): H | Promise<H>;
  /** Client-only islands (and re-mount after a hydration error). */
  mount(root: Element, component: C, props: Record<string, unknown>, slots: Record<string, Node[] | null>, ctx: { id: string }): H | Promise<H>;
  update(handle: H, props: Record<string, unknown>): void;
  unmount(handle: H): void;
}

/** The island chunk's module: the framework component + its client adapter (generated by the bridge Vite plugin). */
export interface IslandModule {
  default: unknown;
  adapter: ClientAdapter;
  /** Island key (`<module>#<export>`, generated island modules): dev HMR re-hydrates and keeps islands by it. */
  __rivetIsland?: string;
}

/** `client=` policies (spec §3.5). */
export type ClientOn = "load" | "idle" | "visible" | "interaction" | "intent" | "only" | `media:${string}`;
/** `client="visible"` or the object form `client={{ on: "visible", rootMargin: "200px" }}`. */
export type ClientPolicy = ClientOn | ({ on: ClientOn } & Record<string, unknown>);
/** Preload strategies (`preload=`, same values as the `preload` directive). */
export type PreloadStrategy = "eager" | "idle" | "visible" | "intent" | "interaction";

/** What the hydration effect captures (resume state): the normalized policy plus the island id. */
export interface PolicyOptions {
  readonly id: string;
  /** Policy; absent = static island with live props (hydrate on the first prop change, spec §3.6). */
  readonly on?: ClientOn;
  readonly [option: string]: unknown;
}

/** One island export, as the generated facade declares it (server variant: `c` + `a`). */
export interface IslandDef<C = unknown> {
  /** `<moduleId>#<export>`. */
  id: string;
  /** The framework component (server facade). */
  c?: C;
  /** Its server adapter (server facade). */
  a?: ServerAdapter<C>;
  /** Island key echoed by the facade; unused since M6-CUT (the derived model resolves chunks through manifest `islands` by `id`). */
  chunk?: string;
  /** Head sink for hoisted entries (`@rivetjs/kit` `pushHead`, passed by the facade when the app uses kit). */
  head?: (head: IslandHead) => ServerValue;
}

/** Identity helper that types an adapter object. */
export const defineAdapter = <C, A extends ServerAdapter<C> | ClientAdapter<C>>(adapter: A): A => adapter;

const HOOK = Symbol.for("rivet.devtools");
/**
 * RV2149: a framework threw away an island's server HTML and rendered it on the client (React `onRecoverableError`, a
 * Vue / Preact hydration mismatch). `console.error` with the code, the framework and the island id (every build); dev:
 * also an `error.island` event on the devtools hook (`@rivetjs/devtools` lists it with the errors, the island root
 * as its element).
 */
export function islandRecovered(framework: string, id: string, error: unknown, root?: Element): void {
  const message = "[RV2149] " + framework + " island " + id + " recovered from an error: " + String((error as Error | null)?.message ?? error);
  if (DEV)
    (globalThis as { [HOOK]?: { emit(type: string, data: object): void } })[HOOK]?.emit("error.island", { framework, id, message, element: root, error });
  console.error(message, error);
}
