export interface CodegenOptions {
  /** Routes directory relative to the project root, posix (e.g. `src/routes`). */
  routesDir: string;
  /** Output directory relative to the project root, posix (default `.rivet`). */
  outDir?: string;
  /** Root-relative module whose default export is the `DocumentShell`; re-exported by the server entry. */
  document?: string;
  /**
   * `server` (default): client navigation uses the data endpoint. `static`: prerendered `_data.json`
   * files. `csr`: no server; pages mount in the browser without loader data (`.server.ts` is an error).
   */
  mode?: "server" | "static" | "csr";
  /**
   * `components`: component head (`@rivetjs/kit`): layouts and pages render under their `HeadLevel`,
   * client navigation applies route heads, and the server entry hands the request's head sink to the
   * app (the handler holds the document start until the shell rendered).
   */
  head?: "components";
  /** Route transitions + pending UI (`@rivetjs/router/transitions`, loaded on first navigation intent). */
  transitions?: boolean | TransitionOptions;
  /** Route announcer (a live region given each new page's title after client navigation). Default true. */
  announce?: boolean;
  /** URL base path (`/app`, Vite's `base`): route patterns of the generated files carry it (types do not). */
  base?: string;
  /**
   * The app reads search params (`useSearchParams()` / `SearchParams`): the server entry provides the
   * request's and the resume entry the browser's. Off: none of it ships (the Vite plugin detects it).
   */
  searchParams?: boolean;
  /**
   * The app calls `navigate()` / `invalidate()` / `revalidate()` / `setSearchParams()` (or uses
   * `@rivetjs/forms`): the App serves them (`rivet:go` listener, `data-rivet-go` on the routes element).
   * Off: no listener, no resume state; calls load the document.
   */
  navigate?: boolean;
  /**
   * The app uses `@rivetjs/forms` (implies `navigate`): every router handler first installs the router brand
   * (`_brand(_go)`, `Symbol.for("rivet.router")`) forms reach the router through. Off: no brand, no `_go`.
   */
  forms?: boolean;
  /** The app reads `useParams()`: pages and persisted layouts render under the params context. */
  params?: boolean;
  /** The app renders `<Link active>`: the App re-marks active links after each client navigation (`_markActive`). */
  activeLinks?: boolean;
  /**
   * Document prefetch (`@rivetjs/router/prefetch`): the server entry wraps the document shell so every
   * page's head carries the Speculation Rules + inline fallback; a string is also the default for unmarked links.
   */
  prefetch?: boolean | DocumentPrefetch;
  /** Speculation Rules eagerness when `prefetch` is on (absent: `moderate`). */
  prefetchEagerness?: PrefetchEagerness;
  /** `false`: no route-path RegExp in the prefetch rules (only reload / external links take part). */
  prefetchPaths?: boolean;
  /** `"never"` / `"always"`: the server entry exports the policy (page requests in the other form answer 308). */
  trailingSlash?: TrailingSlash;
  /** `rivetRouter({ preload: { background } })`: the server entry exports it (the app's default background budget). */
  preloadBackground?: number;
  /** `rivetRouter({ routeRules })`: the server entry exports them (JSON data). */
  routeRules?: Readonly<Record<string, unknown>>;
  /**
   * `rivetRouter({ clientRouter })`: `false` marks the App's router listeners `standalone: false` (alone
   * they do not make a page resumable: inert pages ship zero JS). Default: `false` in `static` mode.
   */
  clientRouter?: boolean;
}
export interface Generated {
  /** File name (relative to outDir) → contents. */
  readonly files: Readonly<Record<string, string>>;
  /** Root-relative modules that must compile in resume mode (generated app + route components). */
  readonly resumeModules: readonly string[];
}

