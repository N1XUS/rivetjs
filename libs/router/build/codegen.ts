// Characters a browser-serialized `URL.pathname` holds percent-encoded: the WHATWG path percent-encode
// set, non-ASCII, and `%` (decoded text: a literal `%` is written `%25`).
const ENCODED = /[\0- "#%<>?`{}\x7f-\uffff]/;
// RegExp syntax characters (escaped the way `u` / `v` mode RegExps — and URLPattern regexp groups — accept).
const SYNTAX = /[\\^$.*+?()[\]{}|/]/g;
/** One static path segment as a browser-serialized `URL.pathname` holds it, RegExp-escaped. */
function literal(segment: string): string {
  let text: string;
  try {
    text = decodeURIComponent(segment);
  } catch {
    text = segment;
  }
  return [...text]
    .map((char) => (ENCODED.test(char) ? encodeURIComponent(char).replace(/%[\da-f]{2}/gi, (escape) => escape.toUpperCase()) : char))
    .join("")
    .replace(SYNTAX, "\\$&");
}
/** Whether some URL path could match both route patterns (static segments differ → no). */
function overlaps(a: string, b: string): boolean {
  const left = a.split("/").filter(Boolean),
    right = b.split("/").filter(Boolean);
  for (let i = 0; ; i++) {
    const x = left[i],
      y = right[i];
    if (x?.[0] === "*" || y?.[0] === "*") return true;
    if (x === undefined || y === undefined) return x === y;
    if (x[0] !== ":" && y[0] !== ":" && x !== y) return false;
  }
}
type Trie = { end: boolean; splat: boolean; param?: Trie; kids: Map<string, Trie> };
const trie = (): Trie => ({ end: false, splat: false, kids: new Map() });

