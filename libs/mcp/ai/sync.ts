// AI instruction files from one source (this folder): `agents.md` (full app-author instructions), `digest.md` (short
// rules), `skills/*.md` (task skills, frontmatter `name` + `description`). Generates, per starter template
// (`templates/starter-*`, copied by create-rivet into every new app):
//   AGENTS.md + CLAUDE.md (same text), .github/copilot-instructions.md, .cursor/rules/rivet.mdc (always) +
//   .cursor/rules/<skill>.mdc (agent-requested), .agents/skills/<skill>/ + .claude/skills/<skill>/;
// public `skills/<skill>/` bundles are installable independently; `skills/<id>/` beside a source Markdown holds resources.
// and the Claude Code plugin `libs/mcp/plugin/` (skills + the MCP server) with its marketplace
// `libs/mcp/.claude-plugin/marketplace.json`.
//   node libs/mcp/ai/sync.ts [--check]
// `--check`: no writes; fails when a generated file is missing, differs or is stale (left over from a removed skill).
import { existsSync, readdirSync, readFileSync, rmSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import * as prettier from "prettier";

const HERE = import.meta.dirname;
export const REPO = resolve(HERE, "../../..");

export interface Skill {
  /** File id (`add-route`). */
  id: string;
  /** Frontmatter `name` (`rivet-add-route`). */
  name: string;
  description: string;
  /** Markdown after the frontmatter. */
  body: string;
  /** Optional companion directory, paths relative to the installed skill root. */
  resources: Record<string, string>;
}

/** Parse `skills/<id>.md` (frontmatter `name`, `description`; single-line values). */
export function readSkills(dir = join(HERE, "skills")): Skill[] {
  return readdirSync(dir)
    .filter((file) => file.endsWith(".md"))
    .sort()
    .map((file) => {
      const text = readFileSync(join(dir, file), "utf8");
      const match = /^---\n([\s\S]*?)\n---\n+([\s\S]*)$/.exec(text);
      if (!match) throw new Error(`libs/mcp/ai/skills/${file}: frontmatter (--- name / description ---) required`);
      const field = (key: string) => {
        const value = new RegExp(`^${key}:\\s*(.+)$`, "m").exec(match[1]!)?.[1]?.trim();
        if (!value) throw new Error(`libs/mcp/ai/skills/${file}: frontmatter "${key}" required`);
        return value;
      };
      const name = field("name");
      if (!/^[a-z0-9-]{1,64}$/.test(name)) throw new Error(`libs/mcp/ai/skills/${file}: name must be lowercase letters, digits, hyphens (≤ 64)`);
      const description = field("description");
      if (description.length > 1024) throw new Error(`libs/mcp/ai/skills/${file}: description over 1024 characters`);
      const id = file.replace(/\.md$/, "");
      const resourceDir = join(dir, id);
      const resources: Record<string, string> = {};
      if (existsSync(resourceDir)) {
        for (const entry of readdirSync(resourceDir, { recursive: true, withFileTypes: true })) {
          if (!entry.isFile()) continue;
          const path = relative(resourceDir, join(entry.parentPath, entry.name)).split("\\").join("/");
          if (path === "SKILL.md" || path === "LICENSE.txt") throw new Error(`${resourceDir}/${path}: reserved generated file`);
          resources[path] = readFileSync(join(resourceDir, path), "utf8");
        }
      }
      return { id, name, description, body: match[2]!.trimEnd() + "\n", resources };
    });
}

const note = (source: string) =>
  `<!-- Generated by libs/mcp/ai/sync.ts from libs/mcp/ai/${source} in the Rivet repository: edit the source there and run the script. In an app created from a starter this file is yours to edit. -->\n\n`;
const yaml = (value: string) => JSON.stringify(value);

/** Every generated file: repo-relative path → contents, Markdown / JSON formatted with the repo's Prettier config. */
export async function aiOutputs(repo = REPO): Promise<Map<string, string>> {
  const agents = readFileSync(join(HERE, "agents.md"), "utf8");
  const digest = readFileSync(join(HERE, "digest.md"), "utf8");
  const skills = readSkills();
  const files = new Map<string, string>();
  const skillFile = (skill: Skill) => `---\nname: ${skill.name}\ndescription: ${yaml(skill.description)}\n---\n\n${note(`skills/${skill.id}.md`)}${skill.body}`;
  const license = readFileSync(join(repo, "LICENSE"), "utf8");
  const bundle = (root: string, skill: Skill) => {
    files.set(`${root}/SKILL.md`, skillFile(skill));
    files.set(`${root}/LICENSE.txt`, license);
    for (const [path, contents] of Object.entries(skill.resources)) files.set(`${root}/${path}`, note(`skills/${skill.id}/${path}`) + contents);
  };
  for (const skill of skills) bundle(`skills/${skill.name}`, skill);
  const starters = readdirSync(join(repo, "templates"), { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && entry.name.startsWith("starter-"))
    .map((entry) => entry.name)
    .sort();
  for (const starter of starters) {
    const at = (path: string) => `templates/${starter}/${path}`;
    files.set(at("AGENTS.md"), note("agents.md") + agents);
    files.set(at("CLAUDE.md"), note("agents.md") + agents);
    files.set(at(".github/copilot-instructions.md"), note("digest.md") + digest);
    files.set(
      at(".cursor/rules/rivet.mdc"),
      `---\ndescription: ${yaml("Rivet framework rules (not React / Solid)")}\nglobs:\nalwaysApply: true\n---\n\n${note("digest.md")}${digest}`,
    );
    for (const skill of skills) {
      files.set(
        at(`.cursor/rules/${skill.name}.mdc`),
        `---\ndescription: ${yaml(skill.description)}\nglobs:\nalwaysApply: false\n---\n\n${note(`skills/${skill.id}.md`)}${skill.body.replaceAll("](references/", `](../../.agents/skills/${skill.name}/references/`)}`,
      );
      bundle(at(`.agents/skills/${skill.name}`), skill);
      bundle(at(`.claude/skills/${skill.name}`), skill);
    }
  }
  // Claude Code plugin (skills + MCP server) and a marketplace listing it (`/plugin marketplace add <repo>/libs/mcp`).
  const plugin = {
    name: "rivet",
    description:
      "Rivet design and framework skills (UI/CDK design, routes, forms in drawers, React ports, UI pages, resumability fixes) and the Rivet MCP server (docs search, components, compiler checks).",
    version: "0.0.0-experimental",
    homepage: "https://github.com/rivetjs/rivet",
    license: "MIT",
    keywords: ["rivet", "jsx", "resumable", "mcp"],
  };
  files.set("libs/mcp/plugin/.claude-plugin/plugin.json", JSON.stringify(plugin, null, 2) + "\n");
  files.set("libs/mcp/plugin/.mcp.json", JSON.stringify({ mcpServers: { rivet: { command: "npx", args: ["-y", "@rivetjs/mcp"] } } }, null, 2) + "\n");
  for (const skill of skills) bundle(`libs/mcp/plugin/skills/${skill.name}`, skill);
  files.set(
    "libs/mcp/.claude-plugin/marketplace.json",
    JSON.stringify({ name: "rivet", owner: { name: "Rivet" }, plugins: [{ name: "rivet", source: "./plugin", description: plugin.description }] }, null, 2) +
      "\n",
  );
  for (const [path, contents] of files) {
    if (!/\.(md|json)$/.test(path)) continue;
    const filepath = join(repo, path);
    files.set(path, await prettier.format(contents, { ...(await prettier.resolveConfig(filepath)), filepath }));
  }
  return files;
}

/** Generated files on disk that no longer have a source (removed skills), repo-relative. */
export function staleOutputs(expected: ReadonlyMap<string, string>, repo = REPO): string[] {
  const stale: string[] = [];
  const scan = (dir: string, match: (rel: string) => boolean) => {
    const abs = join(repo, dir);
    if (!existsSync(abs)) return;
    for (const entry of readdirSync(abs, { recursive: true, withFileTypes: true })) {
      if (!entry.isFile()) continue;
      const rel = relative(repo, join(entry.parentPath, entry.name)).split("\\").join("/");
      if (match(rel) && !expected.has(rel)) stale.push(rel);
    }
  };
  for (const starter of new Set([...expected.keys()].filter((path) => path.startsWith("templates/")).map((path) => path.split("/").slice(0, 2).join("/")))) {
    scan(`${starter}/.claude/skills`, (rel) => /\/skills\/rivet-[^/]+\//.test(rel));
    scan(`${starter}/.agents/skills`, (rel) => /\/skills\/rivet-[^/]+\//.test(rel));
    scan(`${starter}/.cursor/rules`, (rel) => /\/rivet(-[^/]+)?\.mdc$/.test(rel));
  }
  scan("libs/mcp/plugin", () => true);
  scan("skills", (rel) => /^skills\/rivet-[^/]+\//.test(rel));
  return stale.sort();
}

/** Differences between the generated files and the repository (`missing` / `differs` / `stale` + path). */
export async function aiProblems(repo = REPO): Promise<string[]> {
  const expected = await aiOutputs(repo);
  const problems: string[] = [];
  for (const [path, contents] of expected) {
    const file = join(repo, path);
    if (!existsSync(file)) problems.push(`missing ${path}`);
    else if (readFileSync(file, "utf8") !== contents) problems.push(`differs ${path}`);
  }
  for (const path of staleOutputs(expected, repo)) problems.push(`stale ${path}`);
  return problems;
}

if (import.meta.main) {
  const expected = await aiOutputs();
  if (process.argv.includes("--check")) {
    const problems = await aiProblems();
    if (problems.length) {
      console.error(`ai sync --check: ${problems.length} problem(s) (run node libs/mcp/ai/sync.ts)\n  ${problems.join("\n  ")}`);
      process.exit(1);
    }
    console.log(`ai sync --check: ok, ${expected.size} files`);
  } else {
    let written = 0;
    for (const [path, contents] of expected) {
      const file = join(REPO, path);
      if (existsSync(file) && readFileSync(file, "utf8") === contents) continue;
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, contents);
      written++;
    }
    const stale = staleOutputs(expected);
    for (const path of stale) rmSync(join(REPO, path));
    console.log(`ai sync: ${expected.size} files, ${written} written, ${stale.length} stale removed`);
  }
}
