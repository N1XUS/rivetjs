// Compiles the per-component stylesheets of @rivetjs/ui (identity spec docs/design/specs/2026-10-11-ui-identity-design.md
// §3.4: CSS ships with the component that uses it) into libs/ui/styles/out/:
//   out/<name>.css   styles/components/<name>.css compiled with Tailwind v4 against the shared theme, utilities and
//                    variants by reference (nothing of them emitted), nesting lowered (Tailwind's browser targets), in
//                    the cascade layer `components` (after Tailwind's layer order statement), + the `@keyframes` /
//                    `@property` rules it uses. Imported by `styles/src/components/<name>/<name>.styles.ts`: the CSS
//                    graph is the JS import graph. One shared layer, not a sub-layer per file: cross-file overrides
//                    rely on specificity (`.radio-group--secondary .radio__control` beats radio.css's
//                    `.radio__control`), which a later sub-layer would override. Equal-specificity conflicts between
//                    files would depend on load order: `tests/styles-split.test.ts` asserts there are none.
//   out/theme.css    the Tailwind theme variables the components read (`@layer theme`) + the `@layer properties`
//                    fallback of their `--tw-*` variables (`styles/index.css` imports it; a site that compiles its
//                    own Tailwind and imports components without `@rivetjs/ui/styles` imports it too: the docs sites).
//                    Component files read `var(--x)` without fallbacks (inlined theme fallbacks doubled their bytes).
//   out/base.css     `styles/index.css` compiled (Tailwind preflight, theme tokens, base, scrollbar):
//                    the plain-CSS entry for apps without Tailwind.
//   out/all.css      base.css + every component (CDN / no bundler), each `@keyframes` / `@property` once.
// Identity: `tests/styles-split.test.ts` (the union of the out files = the single bundle `styles/index.css` +
// `components/index.css` compiles to, rule for rule).
// Usage: node libs/ui/scripts/build-css.ts [--check]   (--check: exit 1 when a committed out file is stale)
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { compile, optimize } from "@tailwindcss/node";
import postcss, { type AtRule, type ChildNode, type Root } from "postcss";

const STYLES = fileURLToPath(new URL("../styles/", import.meta.url));
const OUT = STYLES + "out/";
const GENERATED = (from: string) => `/* Generated by libs/ui/scripts/build-css.ts from libs/ui/styles/${from}. Do not edit. */`;

/** Tailwind context of a component file: theme mapping, utilities and custom variants, referenced (emits nothing). */
const REFERENCE = [
  `@reference "tailwindcss";`,
  `@reference "tw-animate-css";`,
  `@reference "./themes/shared/theme.css";`,
  `@reference "./utilities/index.css";`,
  `@reference "./variants/index.css";`,
].join("\n");

/**
 * Tailwind v4's layer order, stated by every component file: a component stylesheet linked before the app's own
 * (a resume chunk's CSS, a dev `<style>`) must not create `components` ahead of `base` (preflight would win).
 */
export const LAYERS = "@layer properties, theme, base, components, utilities;";

/**
 * Crumbs folded into a parent's out file (CSS-TIER 2026-10-12): stylesheets under 600 B whose component never renders
 * without the parent (a section inside its ListBox / Menu, a group around its Checkboxes / Disclosures), so a page
 * links one file less. The child's rules come first in the parent's file (its `components/index.css` position is
 * just before the parent's); the child's tv file imports the parent's out file. A component that renders alone (e.g.
 * `description`, 573 B, in every field) keeps its file.
 */
export const FOLDS: Readonly<Record<string, string>> = {
  "disclosure-group": "disclosure",
  "list-box-section": "list-box",
  "menu-section": "menu",
  "checkbox-group": "checkbox",
};

/** The out file (without `.css`) holding a component's rules. */
export const outName = (name: string): string => FOLDS[name] ?? name;

/** Component file names in `components/index.css` import order (= the single bundle's cascade order). */
export function componentOrder(): string[] {
  const index = readFileSync(STYLES + "components/index.css", "utf8");
  return [...index.matchAll(/^@import "\.\/([a-z0-9-]+)\.css";/gm)].map((m) => m[1]!);
}

/**
 * The provenance header of a component source (`/* Ported from … *\/`, `/* Rivet … *\/`): the leading block comments
 * that start on the file's first two lines, each kept whole (a multi-line comment stays closed in the out file). An
 * unclosed leading comment throws instead of commenting out the rest of the out file.
 */
export function headerComments(source: string, name = "<source>"): string[] {
  const header: string[] = [];
  let at = 0;
  for (;;) {
    const start = source.slice(at).search(/\S/);
    if (start < 0 || !source.startsWith("/*", at + start)) break;
    const open = at + start;
    const close = source.indexOf("*/", open + 2);
    if (close < 0) throw new Error(`build-css: components/${name}.css: unclosed header comment`);
    const line = source.slice(0, open).split("\n").length - 1;
    if (line >= 2) break;
    const comment = source.slice(open, close + 2);
    if (/^\/\* (Ported from|Rivet)/.test(comment)) header.push(comment);
    at = close + 2;
  }
  return header;
}

async function tailwind(css: string): Promise<string> {
  const compiler = await compile(css, { base: STYLES, onDependency() {} });
  return compiler.build([]);
}

/** Nesting lowered for Tailwind's browser targets (what `@tailwindcss/vite` does to an app stylesheet), not minified. */
const lower = (css: string) => optimize(css, { minify: false }).code;

/** `index.css` imports of generated files (dropped from the single bundle, inlined for base.css). */
const OUT_IMPORTS = /^@import "\.\/out\/theme\.css";\n/gm;

/** The single bundle: `styles/index.css` with every component file in layer `components` (the pre-split entry). */
export async function singleBundle(): Promise<string> {
  const index = readFileSync(STYLES + "index.css", "utf8").replace(OUT_IMPORTS, "");
  return lower(await tailwind(index + `\n@import "./components/index.css" layer(components);\n`));
}

const isProperty = (n: ChildNode): n is AtRule => n.type === "atrule" && n.name === "property";
const isKeyframes = (n: ChildNode): n is AtRule => n.type === "atrule" && /^(-webkit-)?keyframes$/.test(n.name);
const isPropertiesLayer = (n: ChildNode) => n.type === "atrule" && n.name === "layer" && n.params === "properties";

/** `@property` / `@keyframes` rules by name, from the single bundle and tw-animate-css (both complete sets). */
function registry(bundle: Root) {
  const properties = new Map<string, string>();
  const keyframes = new Map<string, string>();
  bundle.walkAtRules((rule) => {
    if (rule.name === "property") properties.set(rule.params, rule.toString());
    else if (isKeyframes(rule)) keyframes.set(rule.params, rule.toString());
  });
  return { properties, keyframes };
}

/** Custom properties a stylesheet reads or sets, and the keyframes its `animation` / `animation-name` name. */
function uses(css: string, keyframeNames: Iterable<string>) {
  const vars = new Set(css.match(/--tw-[\w-]+/g) ?? []);
  const frames = new Set<string>();
  for (const name of keyframeNames) if (new RegExp(`animation(-name)?:[^;]*(^|[\\s,(])${name}([\\s,;)]|$)`, "m").test(css)) frames.add(name);
  return { vars, frames };
}

export async function generateCss(): Promise<Record<string, string>> {
  const order = componentOrder();
  const bundle = postcss.parse(await singleBundle());
  const { properties, keyframes } = registry(bundle);
  const files: Record<string, string> = {};
  const allRules: string[] = [];
  const allFrames = new Set<string>();
  const allVars = new Set<string>();
  /** Folded children's compiled parts, by parent. */
  const folded = new Map<string, { name: string; header: string[]; body: string; vars: Set<string>; frames: Set<string> }[]>();

  for (const name of order) {
    const source = readFileSync(`${STYLES}components/${name}.css`, "utf8");
    const header = headerComments(source, name);
    const root = postcss.parse(lower(await tailwind(`${REFERENCE}\n@layer components {\n${source}\n}\n`)));
    // Tailwind's banner, `@layer properties` (statement + fallback block) and `@property` rules come from the registry.
    root.walkComments((c) => void c.remove());
    for (const node of [...root.nodes]) if (isProperty(node) || isPropertiesLayer(node) || isKeyframes(node)) node.remove();
    const body = root.toString().trim();
    const { vars, frames } = uses(body, keyframes.keys());
    allRules.push(body);
    for (const f of frames) allFrames.add(f);
    for (const v of vars) allVars.add(v);
    if (FOLDS[name]) {
      folded.set(FOLDS[name], [...(folded.get(FOLDS[name]) ?? []), { name, header, body, vars, frames }]);
      continue;
    }
    const children = folded.get(name) ?? [];
    for (const child of children) for (const set of ["vars", "frames"] as const) for (const x of child[set]) (set === "vars" ? vars : frames).add(x);
    const extra = [...[...frames].map((f) => keyframes.get(f)!), ...[...vars].filter((v) => properties.has(v)).map((v) => properties.get(v)!)];
    const from = children.length ? `components/{${[...children.map((c) => c.name), name].join(",")}}.css` : `components/${name}.css`;
    files[`${name}.css`] =
      [GENERATED(from), ...new Set([...children.flatMap((c) => c.header), ...header]), LAYERS, ...children.map((c) => c.body), body, ...extra].join("\n") +
      "\n";
  }
  for (const parent of folded.keys()) if (!files[`${parent}.css`]) throw new Error(`build-css: fold parent ${parent} precedes its child`);

  // theme.css: the Tailwind theme variables the components read (`--spacing`, `--text-sm`, `--ease-smooth`,
  // `--border-width-field`, …): Tailwind emits a theme variable only where a compiled stylesheet uses it, and the
  // component files compile against the theme by reference. The single bundle's `@layer theme` `:root` rule.
  const themeRules = bundle.nodes.flatMap((n) =>
    n.type === "atrule" && n.name === "layer" && n.params === "theme" ? (n.nodes ?? []).filter((c) => c.type === "rule").map((c) => c.toString()) : [],
  );
  // + the `@layer properties` fallback (`--tw-*` initial values where `@property` is missing) of every component.
  const propertiesLayer = bundle.nodes.filter(isPropertiesLayer).map((n) => n.toString());
  const themeCss = [...propertiesLayer, `@layer theme {\n  ${themeRules.join("\n  ")}\n}`].join("\n");
  files["theme.css"] = `${GENERATED("index.css + components/*.css (Tailwind theme variables in use)")}\n${themeCss}\n`;

  // base.css: the Tailwind entry (index.css, components arrive per file) compiled once, banner kept.
  const index = readFileSync(STYLES + "index.css", "utf8").replace(OUT_IMPORTS, () => themeCss + "\n");
  const base = lower(await tailwind(index));
  files["base.css"] = `${GENERATED("index.css")}\n${base.trim()}\n`;

  // all.css: base + every component (each keyframe / property once; base already holds the ones it uses).
  const baseRoot = postcss.parse(base);
  const inBase = registry(baseRoot);
  const extra = [
    ...[...allFrames].filter((f) => !inBase.keyframes.has(f)).map((f) => keyframes.get(f)!),
    ...[...allVars].filter((v) => properties.has(v) && !inBase.properties.has(v)).map((v) => properties.get(v)!),
  ];
  files["all.css"] = [GENERATED("index.css + components/*.css"), base.trim(), ...allRules, ...extra].join("\n") + "\n";
  return files;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const files = await generateCss();
  let current: string[] = [];
  try {
    current = readdirSync(OUT).filter((f) => f.endsWith(".css"));
  } catch {}
  const stale = [
    ...Object.entries(files)
      .filter(([f, content]) => {
        try {
          return readFileSync(OUT + f, "utf8") !== content;
        } catch {
          return true;
        }
      })
      .map(([f]) => f),
    ...current.filter((f) => !(f in files)),
  ];
  if (check) {
    for (const f of stale) console.error(`stale: libs/ui/styles/out/${f} (run node libs/ui/scripts/build-css.ts)`);
    if (stale.length) process.exit(1);
    console.log(`ui css: ${Object.keys(files).length} files current`);
  } else {
    mkdirSync(OUT, { recursive: true });
    for (const f of current) if (!(f in files)) rmSync(OUT + f);
    for (const [f, content] of Object.entries(files)) writeFileSync(OUT + f, content);
    console.log(`ui css: wrote ${stale.length} of ${Object.keys(files).length} files in libs/ui/styles/out/`);
  }
}
