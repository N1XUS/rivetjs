// Generates the theme stylesheets of @rivetjs/ui/styles from src/theme (deriveTheme + presets) and the vendored
// HeroUI default theme (styles/themes/default/variables.css):
//   styles/themes/rivet.css   Rivet brand theme (the default of `@rivetjs/ui/styles`): HeroUI default theme + Rivet tokens.
//   styles/themes/scoped.css  The Rivet theme scoped to `[data-ui-theme="rivet"]` (opt-in: a Rivet-themed island on a
//                             page whose own variables differ, e.g. the docs home).
//   styles/themes/presets.css Every THEME_PRESETS entry scoped to `[data-ui-preset="<id>"]` (opt-in: swap a subtree's
//                             whole look by one attribute, the ui-docs `theme-swap` example).
// Usage: node libs/ui/scripts/gen-themes.ts [--check]   (--check: exit 1 when a committed file is stale)

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { DARK_SELECTORS, LIGHT_SELECTORS, RADIUS_CSS, chartPalette, deriveTheme, themeVariables } from "../src/theme/derive.ts";
import { RIVET_BRAND, RIVET_PRESET, THEME_PRESETS, resolveParams } from "../src/theme/presets.ts";

const STYLES = new URL("../styles/", import.meta.url);
const HEADER = "/* Generated by libs/ui/scripts/gen-themes.ts (src/theme RIVET_PRESET + styles/themes/default/variables.css). Do not edit. */";

type Decl = [name: string, value: string];
interface Blocks {
  common: Decl[];
  light: Decl[];
  dark: Decl[];
}

/** Declarations of the common (`:root, :host`), light and dark blocks of the vendored variables.css, in order. */
export function parseVariables(css: string): Blocks {
  const body = css.replace(/\/\*[\s\S]*?\*\//g, "");
  const blocks: Blocks = { common: [], light: [], dark: [] };
  for (const m of body.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    const selector = m[1]!.replace(/\s+/g, " ").trim();
    const target = selector === ":root, :host" ? "common" : selector.startsWith(":root, .light") ? "light" : selector.startsWith(".dark,") ? "dark" : null;
    if (!target) continue;
    for (const d of m[2]!.split(";")) {
      const i = d.indexOf(":");
      if (i < 0) continue;
      const name = d.slice(0, i).trim();
      if (name)
        blocks[target].push([
          name,
          d
            .slice(i + 1)
            .replace(/\s+/g, " ")
            .replace(/\( /g, "(")
            .replace(/ \)/g, ")")
            .trim(),
        ]);
    }
  }
  return blocks;
}

const decls = (list: readonly Decl[], indent: string) => list.map(([n, v]) => `${indent}${n}: ${v};`).join("\n");

const brand: Decl[] = [
  ...Object.entries(RIVET_BRAND).map(([k, v]): Decl => [`--rivet-${k}`, v]),
  [
    "--rivet-gradient",
    "linear-gradient(120deg, var(--rivet-cyan), var(--rivet-blue) 30%, var(--rivet-indigo) 50%, var(--rivet-violet) 65%, var(--rivet-purple) 80%, var(--rivet-magenta) 90%, var(--rivet-pink))",
  ],
];

/** HeroUI's shadow stacks (variables.css) with the black tinted to the Rivet neutral hue, same alpha (spec §3.5). */
const tint = (alpha: number) => `oklch(0.25 0.02 264 / ${alpha})`;
const SHADOWS_LIGHT: Decl[] = [
  ["--surface-shadow", `0 2px 4px 0 ${tint(0.04)}, 0 1px 2px 0 ${tint(0.06)}, 0 0 1px 0 ${tint(0.06)}`],
  ["--overlay-shadow", `0 2px 8px 0 ${tint(0.06)}, 0 -6px 12px 0 ${tint(0.03)}, 0 14px 28px 0 ${tint(0.08)}`],
  ["--field-shadow", `0 2px 4px 0 ${tint(0.04)}, 0 1px 2px 0 ${tint(0.06)}, 0 0 1px 0 ${tint(0.06)}`],
];
/** Dark: cards and overlays get a 1 px hairline at 8 % white (separation by lightness alone was ΔL ≈ 0.02). */
const HAIRLINE = "inset 0 0 0 1px oklch(100% 0 0 / 8%)";
const SHADOWS_DARK: Decl[] = [
  ["--surface-shadow", HAIRLINE],
  ["--overlay-shadow", HAIRLINE],
];

/** Rivet light / dark token lists (derived base tokens + radius + shadows + chart palette), as declarations. */
function rivetDecls() {
  const tokens = deriveTheme(RIVET_PRESET);
  const light: Decl[] = [
    ...(Object.entries(tokens.light) as Decl[]),
    ["--radius", RADIUS_CSS[RIVET_PRESET.radius]],
    ["--field-radius", RADIUS_CSS[RIVET_PRESET.formRadius]],
    ...SHADOWS_LIGHT,
    ...(Object.entries(chartPalette("light")) as Decl[]),
  ];
  const dark: Decl[] = [...(Object.entries(tokens.dark) as Decl[]), ...SHADOWS_DARK, ...(Object.entries(chartPalette("dark")) as Decl[])];
  return { light, dark };
}

export function rivetCss(): string {
  const { light, dark } = rivetDecls();
  return `${HEADER}
/*
 * Rivet brand theme: the HeroUI v3.2.6 default theme (variables, derived hover / soft / border formulas, component
 * customizations) with the Rivet tokens on top: accent from the logo blue / indigo, neutrals tinted toward it,
 * contrast fixes (AA). Logo gradient stops as --rivet-* tokens (+ --color-rivet-* for Tailwind) for special surfaces.
 * Chart palette --chart-1 … --chart-6 (theme tokens: charts, Widget legends, any var(--chart-N)).
 */
@import "./default/index.css";

@layer base {
  :root,
  :host {
${decls(brand, "    ")}
  }

  ${LIGHT_SELECTORS.join(",\n  ")} {
${decls(light, "    ")}
  }

  ${DARK_SELECTORS.join(",\n  ")} {
${decls(dark, "    ")}
  }
}

@theme inline {
${decls(
  Object.keys(RIVET_BRAND).map((k): Decl => [`--color-rivet-${k}`, `var(--rivet-${k})`]),
  "  ",
)}
}
`;
}

/** Dark-mode selectors for a scope: dark ancestor or dark on the scoped element itself. */
const darkScope = (scope: string) => [`.dark ${scope}`, `[data-theme="dark"] ${scope}`, `${scope}.dark`, `${scope}[data-theme="dark"]`];

export function scopedCss(blocks: Blocks): string {
  const { light: rl, dark: rd } = rivetDecls();
  const override = (list: readonly Decl[], over: readonly Decl[]) => {
    const map = new Map(over);
    const out = list.map(([n, v]): Decl => [n, map.has(n) ? map.get(n)! : v]);
    for (const [n, v] of over) if (!list.some(([m]) => m === n)) out.push([n, v]);
    return out;
  };
  // Common block entries (accent / success / radius, …) move into the scoped light block; primitives stay global.
  const PRIMITIVES = new Set(["--white", "--black", "--snow", "--eclipse"]);
  const themed = (common: readonly Decl[]) => common.filter(([n]) => !PRIMITIVES.has(n));
  // The `@theme inline` variables of themes/shared/theme.css that read a token (`--border-width-field`, `--radius-xl`,
  // `--color-field`, …): a component stylesheet reads some of them by name, and at `:root` the scoped tokens are absent.
  const sharedTheme = readFileSync(new URL("themes/shared/theme.css", STYLES), "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
  const derived = [...sharedTheme.matchAll(/^\s*(--[\w-]+):\s*([^;]*var\([^;]*);/gm)].map((m): Decl => [m[1]!, m[2]!.trim()]);
  const heroLight: Decl[] = [["color-scheme", "light"], ...themed(blocks.common), ...blocks.light.filter(([n]) => n !== "color-scheme"), ...derived];
  const heroDark: Decl[] = [["color-scheme", "dark"], ...blocks.dark.filter(([n]) => n !== "color-scheme")];
  const scope = (id: string, light: readonly Decl[], dark: readonly Decl[]) => `  [data-ui-theme="${id}"] {
${decls(light, "    ")}
  }

  ${darkScope(`[data-ui-theme="${id}"]`).join(",\n  ")} {
${decls(dark, "    ")}
  }`;
  return `${HEADER}
/*
 * Opt-in: the Rivet theme scoped to an attribute, for a Rivet-themed island inside a page with other variables.
 *   @import "@rivetjs/ui/styles/themes/scoped.css" layer(theme);
 *   <section data-ui-theme="rivet">…</section>
 * Every token (incl. the derived formulas and the theme variables that read a token, --border-width-field, …) is
 * re-declared on the scoped element: custom properties resolve var() where they are declared. Dark mode: a .dark / [data-theme="dark"] ancestor or on the element itself.
 */
@layer base {
${scope("rivet", override(heroLight, rl), override(heroDark, rd))}
}
`;
}

/** The `@theme inline` variables of themes/shared/theme.css that read a token (re-declared on a scoped element). */
function sharedDerived(): Decl[] {
  const sharedTheme = readFileSync(new URL("themes/shared/theme.css", STYLES), "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
  return [...sharedTheme.matchAll(/^\s*(--[\w-]+):\s*([^;]*var\([^;]*);/gm)].map((m): Decl => [m[1]!, m[2]!.trim()]);
}

/** Shape tokens every preset block sets, so a swap back from a preset that overrides them resets them. */
const SHAPE = ["--border-width", "--field-border-width", "--surface-shadow", "--overlay-shadow", "--field-shadow"] as const;

export function presetsCss(blocks: Blocks): string {
  const vendored = (mode: "light" | "dark") => {
    const map = new Map<string, string>([...blocks.common, ...blocks.light]);
    if (mode === "dark") for (const [n, v] of blocks.dark) map.set(n, v);
    return map;
  };
  const shape = (id: string, mode: "light" | "dark"): Decl[] => {
    const base = vendored(mode);
    if (id === RIVET_PRESET.id) for (const [n, v] of mode === "light" ? SHADOWS_LIGHT : SHADOWS_DARK) base.set(n, v);
    return [...SHAPE.map((n): Decl => [n, base.get(n)!]), ["--surface-backdrop", "none"]];
  };
  const block = (id: string, mode: "light" | "dark") => {
    const vars = themeVariables(resolveParams(THEME_PRESETS.find((p) => p.id === id)!), mode);
    const own = new Map<string, string>([["color-scheme", mode], ...shape(id, mode), ...(mode === "light" ? sharedDerived() : []), ...Object.entries(vars)]);
    return decls([...own], "    ");
  };
  const scope = (id: string) => `  [data-ui-preset="${id}"] {
${block(id, "light")}
  }

  ${darkScope(`[data-ui-preset="${id}"]`).join(",\n  ")} {
${block(id, "dark")}
  }`;
  return `/* Generated by libs/ui/scripts/gen-themes.ts (src/theme THEME_PRESETS + styles/themes/default/variables.css). Do not edit. */
/*
 * Opt-in: every theme preset scoped to an attribute, to swap a subtree's whole look (colours, radii, borders,
 * shadows, backdrop) by changing one attribute; the markup never changes.
 *   @import "@rivetjs/ui/styles/themes/presets.css" layer(theme);
 *   <section data-ui-preset="brutalist">…</section>
 * Presets: ${THEME_PRESETS.map((p) => p.id).join(", ")}. Each block re-declares every variable (themeVariables + shape
 * tokens + the theme variables that read a token): custom properties resolve var() where they are declared. Dark mode:
 * a .dark / [data-theme="dark"] ancestor or on the element itself.
 */
@layer base {
${THEME_PRESETS.map((p) => scope(p.id)).join("\n\n")}
}
`;
}

export function generateThemeFiles(): Record<string, string> {
  const blocks = parseVariables(readFileSync(new URL("themes/default/variables.css", STYLES), "utf8"));
  return { "themes/rivet.css": rivetCss(), "themes/scoped.css": scopedCss(blocks), "themes/presets.css": presetsCss(blocks) };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [path, content] of Object.entries(generateThemeFiles())) {
    const url = new URL(path, STYLES);
    let current = "";
    try {
      current = readFileSync(url, "utf8");
    } catch {}
    if (current === content) continue;
    if (check) {
      console.error(`stale: libs/ui/styles/${path} (run node libs/ui/scripts/gen-themes.ts)`);
      stale++;
    } else {
      writeFileSync(url, content);
      console.log(`wrote libs/ui/styles/${path}`);
    }
  }
  if (stale) process.exit(1);
}
