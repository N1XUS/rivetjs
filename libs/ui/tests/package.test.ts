// `export *` silently drops a name two re-exported modules both define (ambiguous star export): every value a
// component subpath exports must reach the barrel as the same binding.
test("package: every component subpath's value exports reach the index.ts barrel unchanged", async () => {
  installDom();
  const ui: Record<string, unknown> = await import("../index.ts");
  const dirs = readdirSync(new URL("../src/components/", import.meta.url), { withFileTypes: true }).filter((d) => d.isDirectory());
  for (const { name } of dirs) {
    const mod: Record<string, unknown> = await import(`../src/components/${name}/index.ts`);
    for (const key of Object.keys(mod)) assert.equal(ui[key], mod[key], `${name}: ${key}`);
  }
});

