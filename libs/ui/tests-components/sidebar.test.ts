// Sidebar — resumed story app (`/sidebar`): SSR markup with HeroUI-style classes (wrapper, panel, menu buttons sizes /
// outline, badge, sub button, trigger icon), vendored CSS applied (gap width from `--sidebar-width`, floating inner surface
// radius, active menu button background); resumed trigger collapses to the icon width and back (`onOpenChange` log), rail
// toggles, collapsed-only tooltip with the HeroUI tooltip class, `onPress`; mobile sheet (< 768px) opens with the sheet
// classes and closes on Escape; separator margins, collapsed 36 px rows centred, collapse easing; a menu press closes it (ui provider `closeMobileOnAction` default true; cdk: false).
import { test, afterAll, beforeAll } from "vitest";
import assert from "node:assert/strict";
import type { BrowserContext, Page } from "playwright";
import { stories, watch, type Stories } from "./harness.ts";

let s: Stories;
beforeAll(async () => (s = await stories()));
afterAll(async () => s?.close());

async function onPage(body: (page: Page, seen: ReturnType<typeof watch>) => Promise<void>, viewport = { width: 1280, height: 720 }): Promise<void> {
  const context: BrowserContext = await s.browser.newContext({ viewport });
  const page = await context.newPage();
  const seen = watch(page);
  try {
    await page.goto(s.origin + "/sidebar");
    await body(page, seen);
  } finally {
    await context.close();
  }
}

const attr = (page: Page, selector: string, name: string) => page.getAttribute(selector, name);
const width = (page: Page, selector: string) => page.$eval(selector, (el) => el.getBoundingClientRect().width);
const waitState = (page: Page, value: string) =>
  page.waitForFunction((value) => document.querySelector('[data-slot="sidebar"]')?.getAttribute("data-state") === value, value);

test("sidebar: SSR markup carries the HeroUI-style classes", () =>
  onPage(async (page, seen) => {
    assert.match((await attr(page, "#sb-wrapper", "class")) ?? "", /^sidebar-wrapper/);
    const root = page.locator('[data-slot="sidebar"]');
    assert.match((await root.getAttribute("class")) ?? "", /^sidebar\b/);
    assert.equal(await root.getAttribute("data-state"), "expanded");
    assert.equal(await root.getAttribute("data-variant"), "floating");
    assert.equal(await attr(page, "#sb-panel", "class"), "sidebar__container");
    assert.equal(await attr(page, "#sb-home", "class"), "sidebar__menu-button");
    assert.equal(await attr(page, "#sb-home", "data-active"), "true");
    assert.equal(await attr(page, "#sb-lg", "class"), "sidebar__menu-button sidebar__menu-button--lg sidebar__menu-button--outline");
    assert.match((await attr(page, "#sb-badge", "class")) ?? "", /sidebar__menu-badge/);
    assert.match((await attr(page, "#sb-sub", "class")) ?? "", /sidebar__menu-sub-button/);
    assert.match((await attr(page, "#sb-input", "class")) ?? "", /sidebar__input/);
    assert.match((await attr(page, "#sb-trigger", "class")) ?? "", /sidebar__trigger/);
    assert.ok(await page.$('#sb-trigger svg[data-slot="sidebar-trigger-icon"]'));
    assert.equal(await page.textContent("#sb-trigger > span"), "Toggle Sidebar");
    // Visually hidden with the inline style (a `sr-only` class is never generated by the app's Tailwind).
    assert.deepEqual(await page.$eval("#sb-trigger > span", (e) => [getComputedStyle(e).position, e.getBoundingClientRect().width]), ["absolute", 1]);
    await page.waitForLoadState("networkidle");
    assert.deepEqual(seen.errors, []);
  }));

test("sidebar: vendored CSS applied (gap width, floating surface, active item)", () =>
  onPage(async (page) => {
    assert.equal(await width(page, '[data-slot="sidebar-gap"]'), 256);
    assert.notEqual(await page.$eval('[data-slot="sidebar-inner"]', (el) => getComputedStyle(el).borderTopLeftRadius), "0px");
    const bg = (sel: string) => page.$eval(sel, (el) => getComputedStyle(el).backgroundColor);
    assert.notEqual(await bg("#sb-home"), await bg("#sb-inbox"));
    assert.notEqual(await page.$eval("#sb-home", (el) => getComputedStyle(el).borderTopLeftRadius), "0px");
  }));

test("sidebar: resumed trigger collapses to the icon width and back; rail toggles", () =>
  onPage(async (page, seen) => {
    await page.click("#sb-trigger");
    await waitState(page, "collapsed");
    await page.waitForFunction(() => document.getElementById("sb-log")?.textContent === "c");
    assert.equal(await attr(page, '[data-slot="sidebar"]', "data-collapsible"), "icon");
    await page.waitForFunction(() => document.querySelector('[data-slot="sidebar-gap"]')!.getBoundingClientRect().width < 100);
    await page.click("#sb-trigger");
    await waitState(page, "expanded");
    await page.waitForFunction(() => document.querySelector('[data-slot="sidebar-gap"]')!.getBoundingClientRect().width === 256);
    await page.locator("#sb-rail").dispatchEvent("click");
    await waitState(page, "collapsed");
    assert.equal(await page.textContent("#sb-log"), "coc");
    assert.deepEqual(seen.errors, []);
  }));

test("sidebar: separator inside the panel; collapsed rows 36 px centred in the rail; ease-out-quad collapse", () =>
  onPage(async (page) => {
    const rect = (sel: string) => page.$eval(sel, (el) => el.getBoundingClientRect().toJSON() as DOMRect);
    const inner = await rect('[data-slot="sidebar-inner"]');
    const sep = await rect("#sb-sep");
    // mx-2 on both sides (HeroUI `.separator` w-full must not win).
    assert.equal(Math.round(sep.left - inner.left), 8);
    assert.equal(Math.round(inner.right - sep.right), 8);
    assert.equal(await page.$eval('[data-slot="sidebar-gap"]', (el) => getComputedStyle(el).transitionTimingFunction), "cubic-bezier(0.25, 0.46, 0.45, 0.94)");
    await page.click("#sb-trigger");
    await waitState(page, "collapsed");
    await page.waitForTimeout(400);
    const panel = await rect('[data-slot="sidebar-inner"]');
    for (const id of ["#sb-home", "#sb-lg"]) {
      const b = await rect(id);
      assert.deepEqual([Math.round(b.width), Math.round(b.height)], [36, 36], id);
      assert.ok(Math.abs(b.left + b.width / 2 - (panel.left + panel.width / 2)) <= 1, `${id} centred`);
    }
  }));

test("sidebar: collapsed-only tooltip with the HeroUI tooltip class; onPress", () =>
  onPage(async (page) => {
    await page.click("#sb-trigger");
    await waitState(page, "collapsed");
    await page.mouse.move(600, 600);
    await page.hover("#sb-inbox");
    await page.waitForSelector("[role=tooltip]");
    const tooltip = page.locator("[role=tooltip]");
    assert.equal(await tooltip.textContent(), "Inbox");
    assert.match((await tooltip.getAttribute("class")) ?? "", /sidebar__tooltip/);
    await page.click("#sb-inbox");
    await page.waitForFunction(() => document.getElementById("sb-pressed")?.textContent === "1");
  }));

test("sidebar: mobile sheet below 768px opens with the sheet classes; Escape closes", () =>
  onPage(
    async (page, seen) => {
      await page.waitForLoadState("networkidle");
      // Cold page: the desktop panel stays in the markup, hidden by the vendored CSS below 768 px.
      assert.equal(await page.locator("#sb-panel").isVisible(), false);
      await page.click("#sb-trigger");
      await page.waitForSelector("[role=dialog]");
      const sheet = page.locator('[data-mobile="true"]');
      assert.match((await sheet.getAttribute("class")) ?? "", /sidebar__sheet/);
      assert.ok(await page.$(".sidebar__sheet-backdrop"));
      assert.match((await page.locator("[role=dialog]").getAttribute("class")) ?? "", /sidebar__sheet-dialog/);
      await page.keyboard.press("Escape");
      await page.waitForFunction(() => !document.querySelector("[role=dialog]"));
      assert.deepEqual(seen.errors, []);
    },
    { width: 500, height: 800 },
  ));

/** Running CSS transitions of the panel (`panel`) and backdrop (`backdrop`) once both run after `act`: [property, ms, easing]. */
async function overlayTimings(page: Page, act: () => Promise<unknown>, panel: string, backdrop: string): Promise<string[]> {
  await act();
  // A cold page's first click adopts + flushes a task later (first-click defer): wait for both transitions, not a fixed delay.
  await page
    .waitForFunction(
      ([panel, backdrop]) =>
        new Set(
          document
            .getAnimations()
            .filter((a) => a instanceof CSSTransition && (a.effect as KeyframeEffect).target instanceof Element)
            .map((a) => (a.effect as KeyframeEffect).target as Element)
            .filter((el) => el.matches(panel) || el.matches(backdrop)),
        ).size >= 2,
      [panel, backdrop],
      { timeout: 2000, polling: 10 },
    )
    .catch(() => {});
  return page.evaluate(
    ([panel, backdrop]) =>
      document
        .getAnimations()
        .filter((a) => a instanceof CSSTransition && (a.effect as KeyframeEffect).target instanceof Element)
        .map((a) => {
          const el = (a.effect as KeyframeEffect).target as Element;
          const role = el.matches(panel) ? "panel" : el.matches(backdrop) ? "backdrop" : null;
          const t = a.effect!.getTiming();
          return role ? `${role} ${(a as CSSTransition).transitionProperty} ${t.duration}ms ${t.easing}` : null;
        })
        .filter((x): x is string => x != null)
        .sort(),
    [panel, backdrop],
  );
}

// MOTION-HARMONY (TW-186): the mobile sheet slides / fades exactly like a left Drawer (overlay tokens), both ways.
test("sidebar: the mobile sheet enters and exits with a left Drawer's timing", async () => {
  const context: BrowserContext = await s.browser.newContext({ viewport: { width: 500, height: 800 } });
  const page = await context.newPage();
  try {
    await page.goto(s.origin + "/drawer");
    await page.waitForLoadState("networkidle");
    const drawerPanel = '[data-slot="drawer-dialog"]',
      drawerBackdrop = '[data-slot="drawer-backdrop"]';
    const drawerIn = await overlayTimings(page, () => page.click("#dr-left"), drawerPanel, drawerBackdrop);
    await page.waitForTimeout(700);
    const drawerOut = await overlayTimings(page, () => page.keyboard.press("Escape"), drawerPanel, drawerBackdrop);
    await page.goto(s.origin + "/sidebar");
    await page.waitForLoadState("networkidle");
    const sheetPanel = '[data-mobile="true"]',
      sheetBackdrop = ".sidebar__sheet-backdrop";
    const sheetIn = await overlayTimings(page, () => page.click("#sb-trigger"), sheetPanel, sheetBackdrop);
    await page.waitForTimeout(700);
    const sheetOut = await overlayTimings(page, () => page.keyboard.press("Escape"), sheetPanel, sheetBackdrop);
    assert.deepEqual(
      drawerIn.map((t) => t.split(" ").slice(0, 2).join(" ")),
      ["backdrop opacity", "panel translate"],
    );
    assert.deepEqual(sheetIn, drawerIn);
    assert.equal(drawerOut.length, 2);
    assert.deepEqual(sheetOut, drawerOut);
  } finally {
    await context.close();
  }
});

test("sidebar: a swipe dismiss fades the underlay with the stylesheet's exit timing (no JS duration)", () =>
  onPage(
    async (page, seen) => {
      await page.waitForLoadState("networkidle");
      await page.click("#sb-trigger");
      await page.waitForSelector("[role=dialog]");
      await page.waitForTimeout(700);
      const box = (await page.locator('[data-mobile="true"]').boundingBox())!;
      const y = box.y + box.height / 2;
      await page.mouse.move(box.x + box.width - 20, y);
      await page.mouse.down();
      await page.mouse.move(box.x + box.width - 60, y, { steps: 2 });
      await page.mouse.move(box.x + box.width - 160, y, { steps: 3 });
      await page.mouse.up();
      await page.waitForTimeout(40);
      const fades = await page.evaluate(() =>
        document
          .getAnimations()
          .filter((a) => ((a.effect as KeyframeEffect | null)?.target as Element | null)?.matches(".sidebar__sheet-backdrop"))
          .map((a) => `${a.constructor.name} ${a.effect!.getTiming().duration}ms ${a.effect!.getTiming().easing}`),
      );
      // The script fade takes the backdrop's exit transition (overlay tokens) — the same numbers as that CSS transition.
      const script = fades.filter((f) => f.startsWith("Animation "));
      assert.equal(script.length, 1, fades.join(" / "));
      assert.ok(
        fades.some((f) => f.startsWith("CSSTransition ") && f.slice(14) === script[0]!.slice(10)),
        fades.join(" / "),
      );
      await page.waitForFunction(() => !document.querySelector("[role=dialog]"));
      assert.deepEqual(seen.errors, []);
    },
    { width: 500, height: 800 },
  ));

