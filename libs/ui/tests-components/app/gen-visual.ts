// Writes the visual matrix routes `src/routes/visual/<name>.tsx` (gitignored) from `../visual.manifest.ts`: each route
// imports the named demo function of every listed ui-docs example and renders them in order. The example modules are
// copied to `src/visual/<id>.tsx` (gitignored): only modules inside the app compile in resume mode (an import from
// outside the Vite root renders, but its closures do not resume). Run by `buildApp()`.
import { access, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { VISUAL } from "../visual.manifest.ts";

const app = fileURLToPath(new URL("./", import.meta.url));
const repo = fileURLToPath(new URL("../../../../", import.meta.url));
const out = app + "src/routes/visual/";
const demos = app + "src/visual/";

/** Name of the demo function exported inside the example's `#region demo` (`default` for a Rivet-authored example without one). */
async function demoName(id: string): Promise<string> {
  const source = await readFile(`${repo}apps/ui-docs/examples/${id}/src/routes/index.tsx`, "utf8");
  const at = source.indexOf("// #region demo");
  const match = at < 0 ? null : /export function (\w+)/.exec(source.slice(at));
  if (match) return match[1];
  if (/export default function/.test(source)) return "default";
  throw new Error(`gen-visual: ${id} exports no demo function`);
}

/**
 * Relative `../assets/<path>` imports of the copied module → absolute paths: the example's own `src/assets/<path>`, else
 * the shared `examples/_assets/<path>` (the docs-kit rule, `libs/docs-kit/vite.ts`).
 */
async function withAssets(id: string, source: string): Promise<string> {
  const examples = `${repo}apps/ui-docs/examples/`;
  let out = source;
  for (const m of source.matchAll(/from "\.\.\/assets\/([^"?]+)(\?[^"]*)?"/g)) {
    const own = `${examples}${id}/src/assets/${m[1]}`;
    const path = await access(own).then(
      () => own,
      () => `${examples}_assets/${m[1]}`,
    );
    out = out.replace(m[0], `from "${path}${m[2] ?? ""}"`);
  }
  return out;
}

export async function genVisual(): Promise<void> {
  await rm(out, { recursive: true, force: true });
  await rm(demos, { recursive: true, force: true });
  await mkdir(out, { recursive: true });
  await mkdir(demos, { recursive: true });
  for (const entry of VISUAL) {
    const imports: string[] = [];
    const body: string[] = [];
    for (const [i, id] of entry.examples.entries()) {
      await writeFile(`${demos}${id}.tsx`, await withAssets(id, await readFile(`${repo}apps/ui-docs/examples/${id}/src/routes/index.tsx`, "utf8")));
      imports.push(`import { ${await demoName(id)} as D${i} } from "../../visual/${id}.tsx";`);
      body.push(`      <section data-visual="${id}" class="flex justify-center p-6">\n        <D${i} />\n      </section>`);
    }
    await writeFile(
      out + entry.name + ".tsx",
      `// Generated by libs/ui/tests-components/app/gen-visual.ts from visual.manifest.ts. Do not edit.\n${imports.join("\n")}\n\nexport const head = { title: "visual: ${entry.name}" };\n\nexport default function Visual() {\n  return (\n    <div id="visual" class="flex flex-col">\n${body.join("\n")}\n    </div>\n  );\n}\n`,
    );
  }
}
