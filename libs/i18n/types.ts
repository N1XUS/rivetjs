// Generated `.d.ts`: typed keys and params for `t()`, augmenting `Messages`/`Locales` in index.ts.
import { paramsOf, type ParamKind, type Variant } from "./icu.ts";
import type { Table } from "./catalog.ts";

function selectCases(v: Variant, name: string, into: Set<string>): void {
  if (typeof v === "string") return;
  for (const part of v) {
    if ("s" in part && part.s === name) for (const k of Object.keys(part.cases)) if (k !== "other") into.add(k);
    const nested = "cases" in part ? Object.values(part.cases) : "c" in part ? [part.c] : [];
    for (const n of nested) selectCases(n, name, into);
  }
}

// Tags the compiler renders without a param (`MESSAGE_TAGS` in libs/compiler/rust/src/compile.rs): optional.
const NATIVE_TAGS = new Set(["b", "i", "em", "strong", "code", "br", "small"]);

function typeOf(kind: ParamKind, name: string, variants: readonly Variant[]): string {
  switch (kind) {
    case "number":
      return "number";
    case "date":
      return "Date | number";
    case "tag":
      return "(children: Content) => Content";
    case "select": {
      const cases = new Set<string>();
      for (const v of variants) selectCases(v, name, cases);
      return [...[...cases].sort().map((c) => JSON.stringify(c)), "(string & {})"].join(" | ");
    }
    default:
      return "string | number";
  }
}

export function declarations(table: Table, locales: readonly string[]): string {
  const lines = ["// Generated by @rivetjs/i18n. Do not edit.", 'declare module "@rivetjs/i18n" {', "  interface Messages {"];
  let tags = false;
  for (const [key, variants] of Object.entries(table)) {
    const fields = [...paramsOf(variants[0]!)]
      .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
      .map(([name, kind]) => {
        tags ||= kind === "tag";
        const optional = kind === "tag" && NATIVE_TAGS.has(name) ? "?" : "";
        return `${/^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name)}${optional}: ${typeOf(kind, name, variants)}`;
      });
    lines.push(`    ${JSON.stringify(key)}: ${fields.length ? `{ ${fields.join("; ")} }` : "{}"};`);
  }
  if (tags) lines.splice(1, 0, 'import type { Content } from "@rivetjs/runtime/jsx-runtime";');
  lines.push(
    "  }",
    "  interface Locales {",
    ...locales.map((l) => `    ${JSON.stringify(l)}: true;`),
    "  }",
    "}",
    "export {};",
    "",
  );
  return lines.join("\n");
}
