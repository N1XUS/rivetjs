import { defineExample } from "@rivetjs/docs-kit/define.ts";

export default defineExample({
  title: "DateField",
  summary: "A segmented date field: typing fills a segment and moves on, arrow keys spin it, the value is an ISO string in a signal.",
  tags: ["aria", "date", "forms", "keyboard"],
  status: "experimental",
  frame: { height: "sm" },
  show: ["src/routes/index.tsx", "src/styles.css"],
  test: [
    { attr: ["#appt", "role", "group"] },
    { name: ["#appt", "Appointment"] },
    { attr: ["#appt-month", "role", "spinbutton"] },
    { attr: ["#appt-month", "data-placeholder", "true"] },
    { attr: ["#appt-month", "aria-valuetext", "Empty"] },
    { expect: ["#appt", "mm/dd/yyyy"] },
    { described: ["#appt-month", "Type digits or use the arrow keys."] },
    { press: ["#appt-month", "1"] },
    { press: ["#appt-month", "0"] },
    { focused: "#appt-day" },
    { key: "1" },
    { key: "4" },
    { focused: "#appt-year" },
    { key: "2" },
    { key: "0" },
    { key: "2" },
    { key: "6" },
    { expect: ["#value", "Value: 2026-10-14"] },
    { attr: ["#appt-month", "aria-valuetext", "10 – October"] },
    { key: "ArrowLeft" },
    { focused: "#appt-day" },
    { key: "ArrowUp" },
    { expect: ["#value", "Value: 2026-10-15"] },
    { key: "Backspace" },
    { key: "Backspace" },
    { attr: ["#appt-day", "data-placeholder", "true"] },
    // An incomplete date keeps the last complete value (React Stately); the field shows the placeholder.
    { expect: ["#value", "Value: 2026-10-01"] },
    { expect: ["#appt", "10/dd/2026"] },
  ],
});
