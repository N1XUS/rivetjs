import { defineExample } from "@rivetjs/docs-kit/define.ts";

export default defineExample({
  title: "RangeCalendar: commitBehavior",
  summary: "Focus leaving mid-selection: select commits anchor to focused date (default), clear empties the value, reset keeps the previous range.",
  tags: ["cdk", "range-calendar", "options"],
  status: "experimental",
  frame: { height: 569, auto: true },
  show: ["src/routes/index.tsx", "src/styles.css"],
  test: [
    { attr: ["#select", "data-commit-behavior", "select"] },
    { attr: ["#clear", "data-commit-behavior", "clear"] },
    { press: ['#select [data-date="2026-10-12"]', "Enter"] },
    { focused: '#select [data-date="2026-10-13"]' },
    { key: "ArrowRight" },
    { attr: ['#select [data-date="2026-10-12"]', "data-selection-start", "true"] },
    { attr: ['#select [data-date="2026-10-14"]', "data-selection-end", "true"] },
    { click: "#elsewhere" },
    { expect: ["#select-value", "select: 2026-10-12 → 2026-10-14"] },
    { press: ['#clear [data-date="2026-10-12"]', "Enter"] },
    { focused: '#clear [data-date="2026-10-13"]' },
    { key: "ArrowRight" },
    { attr: ['#clear [data-date="2026-10-12"]', "data-selection-start", "true"] },
    { attr: ['#clear [data-date="2026-10-14"]', "data-selection-end", "true"] },
    { click: "#elsewhere" },
    { expect: ["#clear-value", "clear: none"] },
    { press: ['#reset [data-date="2026-10-12"]', "Enter"] },
    { focused: '#reset [data-date="2026-10-13"]' },
    { key: "ArrowRight" },
    { attr: ['#reset [data-date="2026-10-12"]', "data-selection-start", "true"] },
    { attr: ['#reset [data-date="2026-10-14"]', "data-selection-end", "true"] },
    { click: "#elsewhere" },
    { attr: ['#reset [data-date="2026-10-05"]', "data-selection-start", "true"] },
    { attr: ['#reset [data-date="2026-10-12"]', "data-selection-start", null] },
    { expect: ["#reset-value", "reset: 2026-10-05 → 2026-10-06"] },
  ],
});
