export const metrics = [
  "htmlBytes",
  "htmlTransferBytes",
  "jsBytes",
  "jsRequests",
  "inlineScriptBytes",
  "cpuBeforeInput",
  "fcp",
  "lcp",
  "inputToPaint",
  "inputToMutation",
  "tbt",
] as const;
export function summarize(result: RealResult) {
  const table: Record<string, Record<string, { median: number; min: number; max: number; n: number }>> = {};
  for (const condition of result.conditions)
    for (const page of result.pages)
      for (const lane of result.lanes) {
        const rows = result.runs.filter((r) => r.lane === lane && r.page === page && r.condition === condition);
        if (rows.length !== result.repeats || result.errors.some((e) => e.lane === lane && e.page === page)) continue;
        table[`${condition}/${page}/${lane}`] = Object.fromEntries(
          metrics.map((metric) => {
            const values = rows.map((r) => r[metric]);
            return [metric, { median: median(values), min: Math.min(...values), max: Math.max(...values), n: values.length }];
          }),
        );
      }
  return table;
}
