    "",
    "Fast is unthrottled. Slow is the existing Slow 4G profile (150 ms latency, 1.6 Mbps down, 750 kbps up) plus 4× CPU. Before-input window ends after load + 1,000 ms. HTML bytes are UTF-8 source bytes; HTML transfer and external JS bytes use CDP encodedDataLength (compressed transfer including headers). Inline executable script bytes are shown separately and are already included in HTML. JS requests include JavaScript preload/prefetch responses completed before input. CPU is CDP TaskDuration before input (renderer main-thread task time, not server CPU). FCP/LCP are browser observers up to the input cutoff; TBT is sum(max(long-task duration − 50 ms, 0)) from FCP to cutoff, not Lighthouse's TTI window. No coverage/tracing overhead in these samples, symmetric in every lane. All cells are median (min–max); bytes/requests unitless, time metrics ms.",
    "",
    "Server RSS: N/A. resume-bench serves prerendered files and does not measure a per-framework SSR process or RSS; static server memory would not be framework SSR memory. No runtime/compiler changes were made, so this is a workload comparison, not an A/B runtime optimization claim.",
    "",
