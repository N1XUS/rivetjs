// Writes src/components/home/ShowcasePreview.tsx: the static first paint of the home components stage. The live panel
// (Showcase.tsx, @rivetjs/ui) is client-only: it mounts on the first pointer / focus / touch on the stage
// (ShowcaseStage.tsx), so the page ships no resume state for it. The preview is the live panel's own markup, captured
// from the BUILT site in Chromium and converted to static JSX (no handlers, no signals, nothing serialized).
//   node apps/docs/scripts/showcase-preview.ts          capture + write (then rebuild)
//   node apps/docs/scripts/showcase-preview.ts --check  exit 1 when the preview no longer matches the live panel
// tests/home.test.ts runs the same comparison (`panelSignature`).
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createServer } from "node:http";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
export const PREVIEW_FILE = resolve(root, "src/components/home/ShowcasePreview.tsx");

/** Resume / runtime attributes and interaction states that never belong in static markup. */
const DROP = ["data-r", "data-rk", "data-live", "data-hovered", "data-pressed", "data-focused", "data-focus-visible"];

/** In the page: the live panel element → static JSX source (runs inside `page.evaluate`). */
export function panelToJsx(element: Element, drop: string[]): string {
  const text = (value: string) => (/[{}<>&]/.test(value) || /^\s|\s$/.test(value) ? `{${JSON.stringify(value)}}` : value);
  const attr = (name: string, value: string) => {
    if (name === "style") {
      const entries = value
        .split(";")
        .map((part) => part.trim())
        .filter(Boolean)
        .map((part) => {
          const colon = part.indexOf(":");
          return `${JSON.stringify(part.slice(0, colon).trim())}: ${JSON.stringify(part.slice(colon + 1).trim())}`;
        });
      return `style={{ ${entries.join(", ")} }}`;
    }
    if (value === "" && /^(checked|selected|disabled|hidden|multiple|readonly)$/.test(name)) return name;
    return `${name}=${JSON.stringify(value)}`;
  };
  const walk = (node: Node, depth: number): string => {
    if (node.nodeType === Node.TEXT_NODE) return node.textContent ? text(node.textContent) : "";
    if (node.nodeType !== Node.ELEMENT_NODE) return "";
    const el = node as Element;
    const tag = el.localName;
    const attrs = [...el.attributes]
      .filter((a) => !drop.includes(a.name))
      // ID references to elements the live panel renders elsewhere (or never) would dangle in static markup
      .map((a) => (/^aria-(describedby|labelledby|controls)$/.test(a.name) ? { name: a.name, value: a.value.split(/\s+/).filter((id) => element.querySelector(`[id="${id}"]`)).join(" ") } : a))
      .filter((a) => a.value !== "" || !/^aria-/.test(a.name))
      // Generated ids (`rv…` / `rvc…`) renamed: static ids must not collide with ids the page creates before the swap.
      .map((a) => (/^(id|for|aria-(describedby|labelledby|controls))$/.test(a.name) ? { name: a.name, value: a.value.replace(/(^|\s)rvc?(?=\d)/g, "$1lp-preview-") } : a))
      .map((a) => attr(a.name, a.value));
    if (depth === 0) attrs.push('data-preview=""');
    const children = [...el.childNodes].map((child) => walk(child, depth + 1)).join("");
    const open = `<${tag}${attrs.length ? " " + attrs.join(" ") : ""}`;
    return children ? `${open}>${children}</${tag}>` : `${open} />`;
  };
  return walk(element, 0);
}

/** In the page: what must stay equal between preview and live panel (tags, classes, roles, states, text). */
export function panelSignature(element: Element): string[] {
  const out: string[] = [];
  const keep = ["class", "role", "aria-checked", "aria-expanded", "aria-valuenow", "data-selected", "data-orientation", "type"];
  const walk = (el: Element) => {
    const own = [...el.childNodes].filter((n) => n.nodeType === Node.TEXT_NODE).map((n) => n.textContent!.trim()).filter(Boolean).join(" ");
    out.push(`${el.localName}${keep.map((name) => (el.hasAttribute(name) ? ` ${name}=${el.getAttribute(name)}` : "")).join("")}${own ? ` "${own}"` : ""}`);
    for (const child of el.children) walk(child);
  };
  walk(element);
  return out;
}

const HEADER = `// Generated by apps/docs/scripts/showcase-preview.ts. Do not edit.
// Static first paint of the home components stage: the live panel's markup (Showcase.tsx), captured from the built
// site. ShowcaseStage.tsx swaps in the live panel on the first pointer / focus / touch.
// @ts-nocheck: attribute values are the DOM's strings, captured verbatim; the element prop types do not apply.
`;

async function capture(): Promise<{ jsx: string; preview: string[] | null; live: string[] }> {
  const { chromium } = await import("playwright");
  const client = resolve(root, "dist/client");
  const types: Record<string, string> = { ".html": "text/html", ".js": "text/javascript", ".css": "text/css", ".svg": "image/svg+xml", ".woff2": "font/woff2" };
  const server = createServer((req, res) => {
    let path = resolve(client, "." + decodeURIComponent(new URL(req.url!, "http://x").pathname));
    if (existsSync(path) && !path.includes(".", path.lastIndexOf("/"))) path = resolve(path, "index.html");
    if (!existsSync(path)) return void res.writeHead(404).end();
    res.writeHead(200, { "content-type": types[path.slice(path.lastIndexOf("."))] ?? "application/octet-stream" }).end(readFileSync(path));
  });
  await new Promise<void>((done) => server.listen(0, "127.0.0.1", done));
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({ viewport: { width: 1300, height: 850 }, bypassCSP: true });
    await page.goto(`http://127.0.0.1:${(server.address() as { port: number }).port}/`, { waitUntil: "load" });
    await page.addScriptTag({ content: `window.__panelToJsx = ${panelToJsx.toString()}; window.__panelSignature = ${panelSignature.toString()};` });
    type Fns = { __panelToJsx: typeof panelToJsx; __panelSignature: typeof panelSignature };
    const preview = await page.evaluate(() => {
      const el = document.querySelector(".lp-stage > [data-preview]");
      return el ? (window as unknown as Fns).__panelSignature(el) : null;
    });
    await page.locator(".lp-stage").hover({ position: { x: 12, y: 12 } });
    await page.waitForSelector(".lp-stage > .lp-stage-panel:not([data-preview])");
    await page.waitForLoadState("networkidle");
    await page.mouse.move(0, 0);
    const [jsx, live] = await page.evaluate((drop) => {
      const el = document.querySelector(".lp-stage > .lp-stage-panel:not([data-preview])")!;
      const fns = window as unknown as Fns;
      return [fns.__panelToJsx(el, drop), fns.__panelSignature(el)] as const;
    }, DROP);
    return { jsx, preview, live };
  } finally {
    await browser.close();
    server.close();
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { jsx, preview, live } = await capture();
  if (process.argv.includes("--check")) {
    if (JSON.stringify(preview) !== JSON.stringify(live)) {
      console.error("ShowcasePreview.tsx no longer matches the live panel: run node apps/docs/scripts/showcase-preview.ts, then rebuild");
      process.exit(1);
    }
  } else {
    writeFileSync(PREVIEW_FILE, `${HEADER}export function ShowcasePreview() {\n  return (\n    ${jsx}\n  );\n}\n`);
    console.log(`wrote ${PREVIEW_FILE} (${jsx.length} chars)`);
  }
}
