// bridge-demo report: results JSON (run.ts) → markdown + json. Pairs (subject vs reference, same verdict rules as
// apps/island-bench: WIN / LOSE at ≥ 1.1× and above the metric's noise floor, else TIE):
//   rivet vs next                         — headline (idiomatic island policies, each framework's default prefetch)
//   rivet-all-load vs next                — fairness control (every island `load`, like Next's client components)
//   rivet-no-prefetch vs next-no-prefetch — no prefetch in either lane
//   rivet vs rivet-full                   — D-lean vs the full resume driver on the same app (a LOSE = regression)
// Hand-written findings live in a notes file appended verbatim (`--notes`); edit it and regenerate, never the output.
//
// Usage: node apps/bridge-demo/report.ts --in results/x.json --out docs/benchmarks/<name> [--notes file.md]
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { relative, resolve } from "node:path";
import { parseArgs } from "node:util";
import type { BrowserStats, LighthouseStats, Results, ServerStats } from "./run.ts";

const { values: args } = parseArgs({ options: { in: { type: "string" }, out: { type: "string" }, notes: { type: "string" } } });
if (!args.in || !args.out) throw new Error("usage: report.ts --in <results.json> --out <path without extension> [--notes <md>]");
const input = resolve(args.in);
const results = JSON.parse(readFileSync(input, "utf8")) as Results;

const PAIRS: [subject: string, reference: string, label: string][] = [
  ["rivet", "next", "headline"],
  ["rivet-all-load", "next", "all `load` (fairness control)"],
  ["rivet-no-prefetch", "next-no-prefetch", "no prefetch"],
  ["rivet", "rivet-full", "D-lean vs full driver"],
];
const ROUTES = ["/", "/orders", "/orders/new"];
/** Column order of every lane table (run.ts `LANES`); unknown lanes last. */
const ORDER = ["rivet", "rivet-all-load", "rivet-no-prefetch", "rivet-full", "next", "next-no-prefetch"];
const ordered = (lanes: string[]) => [...lanes].sort((a, b) => (ORDER.indexOf(a) >>> 0) - (ORDER.indexOf(b) >>> 0));
type Verdict = "WIN" | "LOSE" | "TIE" | "n/a";
/** Lower is better unless `higher`; `floor` = absolute noise floor in the metric's unit. */
function verdict(subject: number | undefined, reference: number | undefined, floor: number, higher = false): Verdict {
  if (subject === undefined || reference === undefined || Number.isNaN(subject) || Number.isNaN(reference)) return "n/a";
  if (Math.abs(subject - reference) <= floor) return "TIE";
  // Normalised to lower-is-better: `mine` beats `theirs` by ≥ 1.1× = WIN.
  const [mine, theirs] = higher ? [reference, subject] : [subject, reference];
  if (mine * 1.1 <= theirs) return "WIN";
  if (theirs * 1.1 <= mine) return "LOSE";
  return "TIE";
}
const ratio = (subject: number | undefined, reference: number | undefined, higher = false) => {
  if (!subject || !reference || Number.isNaN(subject) || Number.isNaN(reference)) return "";
  const r = higher ? subject / reference : reference / subject;
  return r >= 1 ? r.toFixed(2) + "×" : "1/" + (1 / r).toFixed(2) + "×";
};
const kb = (bytes: number | undefined) => (bytes === undefined || Number.isNaN(bytes) ? "—" : (bytes / 1024).toFixed(1));
const ms = (value: number | undefined, digits = 1) => (value === undefined || Number.isNaN(value) ? "—" : value.toFixed(digits));

interface Row {
  section: string;
  route: string;
  metric: string;
  pair: string;
  subject: string;
  reference: string;
  subjectValue: number | undefined;
  referenceValue: number | undefined;
  verdict: Verdict;
}
const rows: Row[] = [];
const md: string[] = [];
const push = (...lines: string[]) => md.push(...lines);

push("# Bridges demo: the same React dashboard in Next.js and in Rivet + `@rivetjs/bridge-react`", "");
push(
  `> Generated by \`apps/bridge-demo/report.ts\` from \`${relative(resolve(args.out, ".."), input)}\` (${results.stamp}). Do not edit; edit the notes file and regenerate.`,
  "",
);
const unlocked = results.host.notes.some((note) => note.includes("no bench lock"));
const loadedHost = results.host.loaded || results.host.notes.some((note) => note.includes("loaded host"));
push(
  "Same React component sources (`apps/bridge-demo/components`), data and CSS in both lanes. Next 16 App Router (RSC for the static parts, client components for the React ones, `next start`, per-request rendering) vs Rivet file routes with the components as React islands (table + form `load`, chart `visible`, user menu `idle`). Spec: `docs/design/specs/2026-10-12-bridges-demo.md`.",
  "",
);
push(
  `- Host: ${unlocked ? "**smoke run (no bench lock)**" : loadedHost ? '**loaded host** (bench lock taken with maxLoad waived): compare ratios, not absolute times. The label covers the whole run: a phase counts as loaded when it started after the run\'s wait for load < 4 expired, whatever the load at its lock (so a lock at 3.78 can read "maxLoad waived")' : "bench lock held"}. ${results.host.notes.join("; ")}.`,
);
push(
  `- Env: ${Object.entries(results.host.env ?? {})
    .map(([k, v]) => `${k}=${v}`)
    .join(", ")}.`,
);
push(
  `- Versions: ${Object.entries(results.versions)
    .map(([k, v]) => `${k} ${v}`)
    .join("; ")}. Versions marked (next) are the pins in \`next/package.json\`; the App Router runs Next's vendored React build.`,
  "",
);

// ---------------------------------------------------------------- JS breakdown (the headline)
const unthrottled = results.browser.unthrottled ?? results.browser[Object.keys(results.browser)[0] ?? ""] ?? {};
push("## JS before the first input, by what the chunks hold (gzip est. KB)", "");
push(
  "Script resources fetched before the first input, after load + idle — fetched, not necessarily executed (next section). Inline scripts (Rivet boot + records ≈ 7 KB, Next RSC payload up to 83 KB) are page bytes, listed in the server rows, not here. Each chunk is counted once under the first category it matches (`run.ts` `CATEGORIES`: a chunk bundles a component with its libraries in both lanes).",
  "",
);
const BREAKDOWN_LANES = ["rivet", "rivet-full", "next"].filter((lane) => results.chunks?.[lane]);
for (const route of ROUTES) {
  const categories = [...new Set(BREAKDOWN_LANES.flatMap((lane) => Object.keys(results.chunks[lane]?.[route] ?? {})))].sort((a, b) =>
    a === "framework" ? 1 : b === "framework" ? -1 : a.localeCompare(b),
  );
  if (!categories.length) continue;
  push(`### \`${route}\``, "");
  push(`| chunk holds | ${BREAKDOWN_LANES.join(" | ")} |`, `| --- | ${BREAKDOWN_LANES.map(() => "---:").join(" | ")} |`);
  for (const category of categories)
    push(
      `| ${category === "framework" ? "framework (fetched)" : category} | ${BREAKDOWN_LANES.map((lane) => kb(results.chunks[lane]?.[route]?.[category] ?? 0)).join(" | ")} |`,
    );
  const total = (lane: string) => Object.values(results.chunks[lane]?.[route] ?? {}).reduce((sum, n) => sum + n, 0);
  push(`| **total fetched** | ${BREAKDOWN_LANES.map((lane) => "**" + kb(total(lane)) + "**").join(" | ")} |`);
  if (results.chunks.next?.[route] && results.chunks.rivet?.[route])
    push(
      "",
      `Total vs next: rivet ${(total("rivet") / total("next")).toFixed(2)}×${results.chunks["rivet-full"]?.[route] ? `, rivet-full ${(total("rivet-full") / total("next")).toFixed(2)}×` : ""}.`,
    );
  push("");
}

// ---------------------------------------------------------------- fetched vs executed
for (const [condition, byLane] of Object.entries(results.executed ?? {})) {
  const lanes = ordered(Object.keys(byLane));
  if (!lanes.length) continue;
  push(`## JS fetched vs executed before the first input (${condition === "fast3g" ? "Fast 3G + 4× CPU" : condition}, gzip est. KB)`, "");
  push(
    "From each lane's warm-up visit with V8 precise coverage: a script counts as executed when its top-level code ran. Fetch-ahead modules (Rivet `data-fo`: low-priority modulepreloads after `load`) are fetched and compiled, never run. Cells: fetched / executed KB (script requests fetched / executed).",
    "",
  );
  push(`| route | ${lanes.join(" | ")} |`, `| --- | ${lanes.map(() => "---:").join(" | ")} |`);
  for (const route of ROUTES) {
    const cells = lanes.map((lane) => {
      const e = byLane[lane]?.[route];
      return e ? `${kb(e.fetchedGzip)} / ${kb(e.executedGzip)} (${e.fetched} / ${e.executed})` : "—";
    });
    push(`| \`${route}\` | ${cells.join(" | ")} |`);
  }
  push("");
}

// ---------------------------------------------------------------- browser
const BROWSER: [
  key: Exclude<keyof BrowserStats, "paint" | "samples">,
  label: string,
  unit: string,
  floor: number,
  format: (n: number | undefined) => string,
][] = [
  ["jsBytesGzipBeforeInput", "JS fetched before input (gzip est.)", "KB", 1024, kb],
  ["jsBytesBeforeInput", "JS fetched before input (raw)", "KB", 2048, kb],
  ["bytesGzipBeforeInput", "bytes before input (gzip est.)", "KB", 1024, kb],
  ["jsRequestsBeforeInput", "JS requests before input", "", 0, (n) => ms(n, 0)],
  ["prefetchBytesBeforeInput", "prefetch bytes before input (raw)", "KB", 1024, kb],
  ["scriptMsUntilIdle", "script CPU until idle (hydration)", "ms", 2, (n) => ms(n)],
  ["cls", "CLS", "", 0.01, (n) => ms(n, 3)],
];
const browserLanes = ordered([...new Set(Object.values(results.browser).flatMap((byLane) => Object.keys(byLane)))]);
for (const [condition, byLane] of Object.entries(results.browser)) {
  push(`## Browser: ${condition === "fast3g" ? "Fast 3G + 4× CPU" : condition}`, "");
  const samples = [...new Set(Object.values(byLane).flatMap((byRoute) => Object.values(byRoute).map((s) => s.samples)))];
  push(
    `Medians over ${samples.join(" / ")} samples per lane and route (fresh context each, lanes interleaved).${loadedHost ? " Loaded host (see Host): compare ratios, not absolute times." : ""} Verdict columns: ${PAIRS.map(([s, r]) => `${s} vs ${r}`).join("; ")}.`,
    "",
  );
  for (const route of ROUTES) {
    const lanes = browserLanes.filter((lane) => byLane[lane]?.[route]);
    if (!lanes.length) continue;
    push(`### \`${route}\``, "");
    const pairs = PAIRS.filter(([s, r]) => lanes.includes(s) && lanes.includes(r));
    push(`| metric | ${lanes.join(" | ")} | ${pairs.map(([s, r]) => `${s} vs ${r}`).join(" | ")} |`);
    push(`| --- | ${lanes.map(() => "---:").join(" | ")} | ${pairs.map(() => ":---:").join(" | ")} |`);
    const metrics: [label: string, get: (stats: BrowserStats) => number | undefined, floor: number, format: (n: number | undefined) => string, unit: string][] =
      [
        ...BROWSER.map(
          ([key, label, unit, floor, format]) =>
            [label, (stats: BrowserStats) => stats[key], floor, format, unit] as [
              string,
              (s: BrowserStats) => number | undefined,
              number,
              (n: number | undefined) => string,
              string,
            ],
        ),
        ...Object.keys(byLane[lanes[0]!]![route]!.paint).map(
          (name) =>
            ["first input → paint: " + name, (stats: BrowserStats) => stats.paint[name], 2, (n: number | undefined) => ms(n), "ms"] as [
              string,
              (s: BrowserStats) => number | undefined,
              number,
              (n: number | undefined) => string,
              string,
            ],
        ),
      ];
    for (const [label, get, floor, format, unit] of metrics) {
      const cells = lanes.map((lane) => format(get(byLane[lane]![route]!)));
      const verdicts = pairs.map(([subject, reference, pairLabel]) => {
        const s = get(byLane[subject]![route]!),
          r = get(byLane[reference]![route]!);
        const v = verdict(s, r, floor);
        rows.push({
          section: "browser " + condition,
          route,
          metric: label,
          pair: pairLabel,
          subject,
          reference,
          subjectValue: s,
          referenceValue: r,
          verdict: v,
        });
        return v === "TIE" || v === "n/a" ? v : `${v} ${ratio(s, r)}`;
      });
      push(`| ${label}${unit ? ` (${unit})` : ""} | ${cells.join(" | ")} | ${verdicts.join(" | ")} |`);
    }
    push("");
  }
}

// ---------------------------------------------------------------- server
const SERVER: [key: keyof ServerStats, label: string, floor: number, format: (n: number | undefined) => string, higher?: boolean][] = [
  ["cpuMsPerPage", "server CPU / page (ms)", 0.05, (n) => ms(n, 2)],
  ["ttfbP50", "TTFB p50 (ms)", 0.1, (n) => ms(n, 2)],
  ["completeP50", "complete p50 (ms)", 0.1, (n) => ms(n, 2)],
  ["rps", "requests / s", 0, (n) => ms(n, 0), true],
  ["peakRssMb", "peak RSS (MB)", 8, (n) => ms(n, 0)],
  ["pageBytes", "page (raw KB)", 512, kb],
  ["pageBytesGzip", "page (gzip est. KB)", 256, kb],
  ["inlineJsBytes", "inline JS in the page (raw KB)", 256, kb],
];
const serverLanes = ordered(Object.keys(results.server));
if (serverLanes.length) {
  push("## Server (per-request SSR, no compression in any lane)", "");
  push(
    `Closed-loop keep-alive client on the same host (localhost), c1 / c10 = 1 / 10 concurrent connections, 3 rounds × 5 s per lane, route and concurrency, lanes interleaved per round; medians over rounds. Server CPU / page = the server process tree's CPU time (user + sys, \`ps\`) delta over the round / requests. Peak RSS = max over rounds of one server process that serves the routes in order (\`/\`, \`/orders\`, \`/orders/new\`): not a per-route figure.${loadedHost ? " Loaded host (see Host): compare ratios, not absolute times." : ""}`,
    "",
  );
  for (const route of ROUTES)
    for (const c of ["c1", "c10"]) {
      const lanes = serverLanes.filter((lane) => results.server[lane]?.[route]?.[c]);
      if (!lanes.length) continue;
      const pairs = PAIRS.filter(([s, r]) => lanes.includes(s) && lanes.includes(r));
      push(`### \`${route}\` ${c}`, "");
      push(`| metric | ${lanes.join(" | ")} | ${pairs.map(([s, r]) => `${s} vs ${r}`).join(" | ")} |`);
      push(`| --- | ${lanes.map(() => "---:").join(" | ")} | ${pairs.map(() => ":---:").join(" | ")} |`);
      for (const [key, label, floor, format, higher] of SERVER) {
        const get = (lane: string) => results.server[lane]![route]![c]![key] as number;
        const verdicts = pairs.map(([subject, reference, pairLabel]) => {
          const v = verdict(get(subject), get(reference), floor, higher);
          rows.push({
            section: "server " + c,
            route,
            metric: label,
            pair: pairLabel,
            subject,
            reference,
            subjectValue: get(subject),
            referenceValue: get(reference),
            verdict: v,
          });
          return v === "TIE" || v === "n/a" ? v : `${v} ${ratio(get(subject), get(reference), higher)}`;
        });
        push(`| ${label} | ${lanes.map((lane) => format(get(lane))).join(" | ")} | ${verdicts.join(" | ")} |`);
      }
      push("");
    }
}

// ---------------------------------------------------------------- lighthouse
const lhLanes = ordered(Object.keys(results.lighthouse ?? {}));
if (lhLanes.length) {
  push("## Lighthouse 13.5.0 (mobile preset: simulated slow 4G + 4× CPU)", "");
  push(
    `Simulated metrics (Lantern) from one unthrottled trace per run; the Chrome binary is in Host. No observed LCP is compared here.${loadedHost ? " Loaded host (see Host): compare ratios, not absolute times." : ""}`,
    "",
  );
  const LH: [key: keyof LighthouseStats, label: string, floor: number, format: (n: number | undefined) => string, higher?: boolean][] = [
    ["score", "performance score", 1, (n) => ms(n, 0), true],
    ["lcp", "LCP (ms)", 50, (n) => ms(n, 0)],
    ["tbt", "TBT (ms)", 10, (n) => ms(n, 0)],
    ["cls", "CLS", 0.01, (n) => ms(n, 3)],
    ["jsBytes", "JS transferred, raw (KB)", 1024, kb],
    ["totalBytes", "total transferred, raw (KB)", 1024, kb],
  ];
  for (const route of ROUTES) {
    const lanes = lhLanes.filter((lane) => results.lighthouse[lane]?.[route]);
    if (!lanes.length) continue;
    const pairs = PAIRS.filter(([s, r]) => lanes.includes(s) && lanes.includes(r));
    push(`### \`${route}\` (median of ${results.lighthouse[lanes[0]!]![route]!.runs} runs)`, "");
    push(`| metric | ${lanes.join(" | ")} | ${pairs.map(([s, r]) => `${s} vs ${r}`).join(" | ")} |`);
    push(`| --- | ${lanes.map(() => "---:").join(" | ")} | ${pairs.map(() => ":---:").join(" | ")} |`);
    for (const [key, label, floor, format, higher] of LH) {
      const get = (lane: string) => results.lighthouse[lane]![route]![key] as number;
      const verdicts = pairs.map(([subject, reference, pairLabel]) => {
        const v = verdict(get(subject), get(reference), floor, higher);
        rows.push({
          section: "lighthouse",
          route,
          metric: label,
          pair: pairLabel,
          subject,
          reference,
          subjectValue: get(subject),
          referenceValue: get(reference),
          verdict: v,
        });
        return v === "TIE" || v === "n/a" ? v : `${v} ${ratio(get(subject), get(reference), higher)}`;
      });
      push(`| ${label} | ${lanes.map((lane) => format(get(lane))).join(" | ")} | ${verdicts.join(" | ")} |`);
    }
    push("");
  }
}

// ---------------------------------------------------------------- build
if (Object.keys(results.build).length) {
  push("## Build", "");
  push("| lane | wall (ms) | peak RSS, process tree (MB) |", "| --- | ---: | ---: |");
  for (const [lane, build] of Object.entries(results.build)) push(`| ${lane} | ${build.ms} | ${build.treePeakRssMb} |`);
  push("");
}

// ---------------------------------------------------------------- tallies + losses
push("## Tallies and losses", "");
for (const [subject, reference, label] of PAIRS) {
  const mine = rows.filter((row) => row.pair === label && row.verdict !== "n/a");
  if (!mine.length) continue;
  const count = (v: Verdict) => mine.filter((row) => row.verdict === v).length;
  push(`- **${label}** (${subject} vs ${reference}): ${count("WIN")} WIN / ${count("TIE")} TIE / ${count("LOSE")} LOSE.`);
  for (const row of mine.filter((r) => r.verdict === "LOSE"))
    push(
      `  - LOSE: ${row.metric} (${row.section}, \`${row.route}\`): ${row.subjectValue?.toFixed(2)} vs ${row.referenceValue?.toFixed(2)} (${ratio(row.subjectValue, row.referenceValue)}).`,
    );
}
push("");
if (args.notes && existsSync(args.notes)) push(readFileSync(args.notes, "utf8").trim(), "");

const out = resolve(args.out);
writeFileSync(out + ".md", md.join("\n"));
writeFileSync(out + ".json", JSON.stringify({ generatedBy: "apps/bridge-demo/report.ts", pairs: PAIRS, results, rows }, null, 2) + "\n");
console.log(`[bridge-demo] report → ${relative(process.cwd(), out)}.{md,json}`);
